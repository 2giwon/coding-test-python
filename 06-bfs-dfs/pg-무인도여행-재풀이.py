# 핵심: "최단"이 아니라 "연결된 덩어리의 크기" → BFS/DFS 둘 다 가능.
#       시작점이 주어지지 않으므로 격자를 훑으며 미방문 육지를 만날 때마다 BFS를 한 번씩 돌려
#       섬 하나를 통째로 소진한다.
#       🔴 visited는 함수 밖에 하나를 두고 공유 — 이미 센 섬을 다시 세지 않기 위해.
#          (미로 탈출은 반대로 호출마다 새로 생성. 같은 "BFS 함수화"인데 방문 표 수명이 반대다)
#       격자가 문자열 배열이라 maps[r][c]는 문자 → int() 변환 필요.
# 리뷰: [1차 09/12] 25분 자력 통과 (힌트 없음).
#       [2차 09/17] 18분 자력 통과. 백지에서 다시 작성, 7/7.
#       🔴 이번 재풀이의 핵심은 시간이 아니라 "visited를 어디 두는가"를 맞힌 것.
#          바로 전날(09/16) 미로 탈출에서는 호출마다 새로 만들었는데, 오늘은 밖에 두고 공유했다.
#          이틀 연속 정반대 구조를 문제에 맞게 골랐다 = 코드를 외운 게 아니라 기준이 생겼다는 뜻.
#       dr/dc를 bfs 밖으로 뺀 것도 1차보다 나아진 점 (호출마다 다시 만들 이유가 없다).
#       남은 개선: ①visited를 True/False로 (거리를 안 쓰므로) ②식량을 "꺼낼 때" 더하면
#                 시작 칸 특수 처리가 사라짐 ③큐에 리스트/튜플이 섞여 있음 → 튜플로 통일
#
# ─────────────────────────────────────────────────────────────────────
# 재풀이 (1차: 2026-09-12 — 25분 자력 통과, 힌트 없음)
#
# ■ 문제 요약
#   격자에 X(바다)와 1~9(육지, 숫자는 그 칸의 식량)가 있다.
#   상하좌우로 이어진 육지가 하나의 "섬"이다. 각 섬의 식량 합을 구해 오름차순으로 반환한다.
#   섬이 하나도 없으면 [-1].
#
#   예: ["X591X", "X1X5X", "X231X", "1XXX1"] → [1, 1, 27]
#
# ■ 이 문제의 신호 — "최단"이 아니다
#   게임맵·미로탈출은 "최단 거리"를 물었다. 이 문제는 "연결된 덩어리의 크기"를 묻는다.
#   최단이 아니므로 BFS든 DFS든 상관없다. 어차피 덩어리를 전부 훑어야 한다.
#
# ■ 시작점이 주어지지 않는다
#   앞선 문제들은 S가 어디인지 격자에 표시돼 있었다. 여기는 없다.
#   → 격자를 처음부터 끝까지 훑으며 "아직 안 가본 육지"를 만날 때마다 BFS를 한 번씩 돌린다.
#     한 번 돌리면 그 섬이 통째로 방문 처리되므로, 다음 훑기에서 같은 섬을 다시 만나지 않는다.
#
# ■ 🔴 함정 — visited를 어디에 두는가 (미로 탈출과 정반대다)
#
#   미로 탈출  : bfs 호출마다 방문 표를 새로 만든다
#                (S→L 에서 밟은 칸을 L→E 에서 다시 밟아야 하므로)
#   무인도 여행 : 방문 표를 함수 밖에 하나 두고 모든 호출이 공유한다
#                (이미 센 섬을 다시 세면 안 되므로)
#
#   같은 "BFS를 함수로 뺀다"인데 방문 표의 수명이 반대다.
#   → 문제가 "구간을 나눠 각각 최단"인지 "전체를 한 번씩만"인지로 판단한다.
#
# ■ 🔴 함정 2 — 격자가 문자열 배열이다
#   maps[r][c] 는 문자 "5" 이지 숫자 5가 아니다. 더하려면 int() 변환이 필요하다.
#
# ■ 1차 때 지적한 개선점 3가지 (이번엔 처음부터 이렇게)
#   ① 방문 표 이름을 visited 로 — 거리를 쓰지 않으므로 True/False 면 충분하다
#   ② `if int(maps[nr][nc]) > 0` 같은 항상 참인 조건을 넣지 않는다 (육지는 1~9)
#   ③ 식량을 "큐에서 꺼낼 때" 더한다 → 시작 칸만 따로 처리하는 코드가 사라진다
#
# ■ 막히면
#   pg-게임맵최단거리.py 의 BFS 뼈대 + "격자를 훑으며 시작점 찾기" 두 개의 조합입니다.
#   1차 풀이(pg-무인도여행.py)는 마지막에 비교용으로만 열어보세요.
#
# ⏱ 목표 20분
# ─────────────────────────────────────────────────────────────────────
from collections import deque  # noqa: F401


def solution(maps):
    # ① 방문 표를 함수 밖에 하나 (모든 BFS 호출이 공유)
    n, m = len(maps), len(maps[0])
    visited = [[-1 for _ in range(m)] for _ in range(n)]

    dr = [1, -1, 0, 0]
    dc = [0, 0, 1, -1]

    # ② bfs(시작좌표) → 그 섬의 식량 합
    def bfs(start):
        startr, startc = start
        food = int(maps[startr][startc])
        queue = deque([start])

        visited[startr][startc] = 0
        while queue:
            r, c = queue.popleft()

            for i in range(4):
                nr, nc = r + dr[i], c + dc[i]

                if nr < 0 or nr >= n or nc < 0 or nc >= m:
                    continue
                if maps[nr][nc] == "X" or visited[nr][nc] > -1:
                    continue

                visited[nr][nc] = 0
                queue.append([nr, nc])
                food += int(maps[nr][nc])

        return food

    # ③ 격자를 훑으며 미방문 육지마다 bfs 호출, 결과를 모아 정렬
    answer = []
    for i in range(n):
        for j in range(m):
            if maps[i][j] == "X":
                continue
            elif visited[i][j] == -1:
                a = bfs((i, j))
                answer.append(a)

    return [-1] if len(answer) <= 0 else sorted(answer)


if __name__ == "__main__":
    # X = 바다, 1~9 = 육지(그 칸의 식량). 상하좌우로 이어진 육지가 한 섬.
    # 각 섬의 식량 합을 오름차순으로. 섬이 없으면 [-1]
    cases = [
        (["X591X", "X1X5X", "X231X", "1XXX1"], [1, 1, 27]),  # 공식 예제
        (["XXX", "XXX", "XXX"], [-1]),  # 🔴 섬이 하나도 없음
        (["1"], [1]),  # 칸 1개짜리 섬
        (["X1X", "1X1", "X1X"], [1, 1, 1, 1]),  # 🔴 대각선은 연결이 아니다 — 섬 4개
        (["999", "9X9", "999"], [72]),  # 도넛 모양 한 덩어리 (9×8 = 72)
        (["X1X", "XXX", "X1X"], [1, 1]),  # 세로로 분리된 섬 2개
        (["12", "34"], [10]),  # 전부 육지 한 덩어리
    ]
    for maps, expected in cases:
        assert solution(maps) == expected, (maps, expected)
    print("모든 케이스 통과")
