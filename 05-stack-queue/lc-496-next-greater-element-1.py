# 문제: https://leetcode.com/problems/next-greater-element-i/
# 핵심: 단조 스택 3단 — 2단(lc-739)과 질문이 같다("내 뒤에서 처음 나오는 더 큰 값").
#       다른 건 둘뿐. ① 답으로 "거리"가 아니라 "값"을 적는다 → 스택에 인덱스 대신 값을 넣어도 된다
#       ② 배열이 2개 → nums2 를 한 번 훑어 대응표(dict)를 만들고, nums1 순서로 꺼낸다.
#       nums1 을 돌며 nums2 를 매번 뒤지면 O(n×m) 이라 단조 스택을 쓴 의미가 사라진다.
#       못 찾은 값은 표에 안 넣고 `greater.get(x, -1)` 의 기본값으로 처리 → 마무리 루프 불필요.
# 리뷰: 자력 통과 (LeetCode 제출도 통과). 사다리 1→2→3단 중 처음으로 "설명을 안 보고" 푼 단계.
#       1단은 보고 풀었고, 2단은 부등호만 바꾸면 되는 수준이었는데, 3단은 자료구조(dict)가
#       하나 더 붙는데도 막히지 않았다 — 패턴이 손에 붙었다는 신호.
#       ⚠️ 로컬 실패는 내 코드가 아니라 템플릿의 기대값 오류였음 (내림차순 케이스, 아래 참조).
#          "테스트가 틀릴 수도 있다"를 의심한 판단이 맞았다.
#       [재풀이: 09/20 — 1·2단과 함께 백지로]
#
# ─────────────────────────────────────────────────────────────────────
# 단조 스택 사다리 3단 (1단 = pg-주식가격.py, 2단 = lc-739-daily-temperatures.py)
#
# ■ 문제 요약
#   배열이 두 개 주어진다. nums1은 nums2의 일부 원소를 뽑아놓은 것이다(값 중복 없음).
#   nums1의 각 값에 대해, "그 값이 nums2에서 있던 자리의 오른쪽에서 처음 나오는 더 큰 값"을 구한다.
#   그런 값이 없으면 -1.
#
#   예: nums1 = [4,1,2],  nums2 = [1,3,4,2]  →  답 [-1, 3, -1]
#
#     nums2 를 펼쳐보면:   1   3   4   2
#                        (0) (1) (2) (3)
#
#     - 4 는 nums2 의 2번 자리. 오른쪽에 2 하나뿐이고 4보다 크지 않다      → -1
#     - 1 은 nums2 의 0번 자리. 오른쪽에 3 이 있고 1보다 크다              → 3
#     - 2 는 nums2 의 3번 자리. 오른쪽에 아무것도 없다                     → -1
#
# ■ 2단(Daily Temperatures)과 같은 것
#   "내 뒤에서 처음으로 나보다 큰 값"을 찾는다 → 완전히 같은 질문이다.
#   줄 서기 구조도 그대로다. 새 값이 오면 줄 맨 뒤부터 물어보고, 나보다 작은 사람을 내보낸다.
#
# ■ 2단과 다른 것 — 딱 두 가지
#
#   ① 🔴 답으로 적는 것이 "거리"가 아니라 "값"이다
#        2단  : days[past] = i - past        ← 며칠 걸렸나 (인덱스 뺄셈)
#        3단  : ???                          ← 그 큰 값 자체
#      그래서 3단은 줄에 "인덱스"를 넣을 필요가 없다. **값을 그대로 넣어도 된다.**
#      (인덱스를 넣어도 풀리지만, 값을 넣으면 코드가 더 짧아진다. 어느 쪽이든 좋다)
#
#   ② 🔴 배열이 두 개다 — 순서가 다르다
#      답을 구하는 곳은 nums2 이고, 답을 꺼내는 순서는 nums1 이다.
#      nums1 을 돌면서 nums2 를 매번 뒤지면 O(n×m) 이 되어 단조 스택을 쓴 의미가 없다.
#
#      → **nums2 를 한 번만 훑어서 "이 값의 답은 저 값" 대응표를 통째로 만들어두고,**
#        그 다음에 nums1 순서로 표에서 꺼내면 된다.
#        대응표는 파이썬 딕셔너리(dict)를 쓴다.  예: {1: 3, 3: 4, 4: -1, 2: -1}
#        (문제가 "값 중복 없음"을 보장하므로 값을 키로 써도 안전하다)
#
# ■ 그래서 전체 모양은 이렇게 2단계가 된다
#     1단계) nums2 를 단조 스택으로 훑어 대응표를 만든다   ← 2단과 거의 같은 코드
#     2단계) nums1 을 돌며 대응표에서 꺼낸다              ← 표에 없으면 -1
#
#   💡 1단계에서 "끝까지 답을 못 받고 줄에 남은 값"들이 생긴다. 그건 오른쪽에 더 큰 값이
#      없었다는 뜻이다. 이 값들의 답을 어떻게 처리할지 생각해보세요.
#      (2단에서 answer 를 [0]*n 으로 시작해 마무리 루프를 없앴던 것과 같은 요령이 쓸 수 있다)
#
# ■ 막히면
#   lc-739-daily-temperatures.py 를 먼저 다시 보세요. 그 코드에서 바뀌는 건
#   "답판에 무엇을 적는가" 한 줄과, 마지막에 nums1 로 꺼내는 부분뿐입니다.
#
# ■ LeetCode 제출 시에는 클래스 안에 넣는다
#     class Solution:
#         def nextGreaterElement(self, nums1: list[int], nums2: list[int]) -> list[int]:
#   여기서는 로컬 실행을 위해 평범한 함수로 둔다.
#
# ⏱ 목표 15분 (Easy 난이도 — 1·2단보다 쉽다)
# ─────────────────────────────────────────────────────────────────────


def nextGreaterElement(nums1, nums2):
    # 1단계: nums2 를 한 번만 훑어 "값 → 다음 큰 값" 대응표를 만든다
    stack = []  # 아직 답을 못 받은 값들 (인덱스가 아니라 값을 넣는다)
    greater = {}

    for num in nums2:
        # 줄 맨 뒤부터 물어본다 — 나보다 작으면 그 사람의 답이 바로 나다
        while stack and stack[-1] < num:
            past = stack.pop()
            greater[past] = num  # 🔴 거리가 아니라 "값"을 적는다 (1·2단과 다른 점)

        stack.append(num)

    # 끝나고 stack 에 남은 값 = 오른쪽에 더 큰 값이 없었던 값.
    # 표에 안 넣고 그냥 두면 아래 get 의 기본값 -1 이 알아서 처리한다
    # (2단에서 answer 를 [0]*n 으로 시작해 마무리 루프를 없앤 것과 같은 요령)

    # 2단계: nums1 순서로 표에서 꺼낸다
    return [greater.get(x, -1) for x in nums1]


if __name__ == "__main__":
    cases = [
        (([4, 1, 2], [1, 3, 4, 2]), [-1, 3, -1]),  # LeetCode 예제 1
        (([2, 4], [1, 2, 3, 4]), [3, -1]),  # 예제 2
        (([1], [1]), [-1]),  # 원소 1개
        # 🔴 내림차순 nums2 — 누구도 오른쪽에 더 큰 값이 없다. 전부 -1.
        #    아무도 답을 못 받고 stack 에 그대로 쌓인 채 끝나는 케이스.
        (([1, 3, 5, 2, 4], [6, 5, 4, 3, 2, 1]), [-1, -1, -1, -1, -1]),
        (([4, 3, 2, 1], [1, 2, 3, 4]), [-1, 4, 3, 2]),  # nums1 이 역순
        (([5], [1, 5, 3, 7]), [7]),  # 사이를 건너뛰어 찾는 경우
    ]
    for (nums1, nums2), expected in cases:
        assert nextGreaterElement(nums1, nums2) == expected, (nums1, nums2, expected)
    print("모든 케이스 통과")
