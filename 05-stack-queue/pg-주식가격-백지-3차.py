# ■ 문제
#   초 단위로 기록된 주식가격이 담긴 배열 prices 가 매개변수로 주어진다.
#   가격이 떨어지지 않은 기간은 몇 초인지를 return 하도록 solution 을 완성하라.
#
#   예: prices = [1, 2, 3, 2, 3]  →  return [4, 3, 1, 1, 0]
#
#     1초 시점의 ₩1 은 끝까지 가격이 떨어지지 않았다            → 4초
#     2초 시점의 ₩2 는 끝까지 가격이 떨어지지 않았다            → 3초
#     3초 시점의 ₩3 은 1초 뒤에 가격이 떨어진다                 → 1초
#     4초 시점의 ₩2 는 1초간 가격이 떨어지지 않았다             → 1초
#     5초 시점의 ₩3 은 더 이상 기록이 없다                      → 0초
#
# ■ 제약 조건
#   prices 의 각 가격 : 1 이상 10,000 이하의 자연수
#   prices 의 길이    : 2 이상 100,000 이하
#
# ■ 진행 방법
#   ⏱ 목표 20분.
#   20분이 지나거나 도저히 막히면 **그때 말해 주면** 힌트를 만들어 준다.
#   힌트·뼈대를 미리 넣지 않았다. 보고 풀면 측정이 안 되기 때문이다.
# ─────────────────────────────────────────────────────────────────────


def solution(prices):
    length = len(prices)
    answer = [0] * length

    stack = []
    for i in range(length):
        while stack and prices[stack[-1]] > prices[i]:
            p = stack.pop()
            answer[p] = i - p

        stack.append(i)

    for time in stack:
        answer[time] = (length - 1) - time

    return answer


if __name__ == "__main__":
    cases = [
        ("공식 예제", [1, 2, 3, 2, 3], [4, 3, 1, 1, 0]),
        ("오름차순", [1, 2, 3, 4, 5], [4, 3, 2, 1, 0]),
        ("내림차순", [5, 4, 3, 2, 1], [1, 1, 1, 1, 0]),
        ("같은 값 4개", [3, 3, 3, 3], [3, 2, 1, 0]),
        ("최소 길이", [1, 2], [1, 0]),
        ("길이 4 혼합", [3, 1, 2, 4], [1, 2, 1, 0]),
        ("길이 5 혼합", [5, 1, 1, 5, 3], [1, 3, 2, 1, 0]),
    ]

    passed = 0
    for name, prices, expected in cases:
        got = solution(prices)
        ok = got == expected
        if ok:
            passed += 1
        mark = "🟢" if ok else "🔴"
        print(f"{mark} {name:<12} prices={str(prices):<22} 기대={expected}")
        if not ok:
            print(f"{'':>3}{'':<12} {'':<22} 실제={got}")

    print(f"\n{passed}/{len(cases)} 통과")


