# ■ 문제 요약
#   기온 배열이 주어진다. 각 날마다 "더 따뜻한 날이 오기까지 며칠 기다려야 하나"를 구한다.
#   그런 날이 영영 없으면 0.
#   예: [73,74,75,71,69,72,76,73] → [1,1,4,2,1,1,0,0]
#       - 0일(73) : 다음날 74가 더 따뜻 → 1
#       - 2일(75) : 71,69,72 는 안 되고 6일(76)에서야 더 따뜻 → 6-2 = 4
#       - 6일(76) : 뒤에 더 따뜻한 날이 없음 → 0
#
# ■ 주식가격과 같은 것
#   "줄 서기" 구조가 그대로다. 새 날이 도착하면 줄 맨 뒤부터 물어보고, 조건에 걸리는 사람을
#   내보내며 답을 적어준다. 그 다음 자기가 줄 맨 뒤에 선다.
#   줄에 넣는 것도 똑같이 "값"이 아니라 "인덱스(며칠째)"다.
#
# ■ 주식가격과 다른 것 — 딱 두 가지
#   ① 🔴 부등호가 반대다
#      주식가격: 내 뒤에서 "더 싼" 값을 찾는다  → 줄 맨 뒤가 나보다 비싸면 내보냄
#      이 문제: 내 뒤에서 "더 따뜻한" 값을 찾는다 → 줄 맨 뒤가 나보다 ??? 면 내보냄
#      (직접 채워보세요. 위 예제 0일(73) → 1일(74)에서 누가 답을 받는지 생각하면 나옵니다)
#
#   ② 🔴 못 찾았을 때의 답이 다르다 → 그래서 마지막 루프가 필요 없다
#      주식가격: 끝까지 안 떨어지면 "마지막 시각까지의 거리" → 끝나고 줄에 남은 사람을 처리했음
#      이 문제: 더 따뜻한 날이 없으면 그냥 0
#      answer 를 [0] * n 으로 시작하면, 줄에 남은 사람은 건드릴 필요가 없다 (이미 0이므로).
#      → 주식가격보다 코드가 오히려 짧아진다
#
# ■ 막히면
#   pg-주식가격.py 상단의 "줄 서기" 설명과 추적표를 다시 보세요. 구조가 같습니다.
#
# ■ LeetCode 제출 시에는 클래스 안에 넣는다
#     class Solution:
#         def dailyTemperatures(self, temperatures: list[int]) -> list[int]:
#   여기서는 로컬 실행을 위해 평범한 함수로 둔다.
# ─────────────────────────────────────────────────────────────────────


def dailyTemperatures(temperatures):
    n = len(temperatures)
    days = [0] * n
    stack = []

    for i in range(n):
        while stack and temperatures[stack[-1]] < temperatures[i]:
            past = stack.pop()
            days[past] = i - past

        stack.append(i)

    return days


if __name__ == "__main__":
    cases = [
        ([73, 74, 75, 71, 69, 72, 76, 73], [1, 1, 4, 2, 1, 1, 0, 0]),  # LeetCode 예제 1
        ([30, 40, 50, 60], [1, 1, 1, 0]),  # 예제 2 — 계속 오름
        ([30, 60, 90], [1, 1, 0]),  # 예제 3
        ([90, 80, 70], [0, 0, 0]),  # 계속 떨어짐 — 아무도 못 찾음
        ([70, 70, 70], [0, 0, 0]),  # 🔴 같은 기온은 "더 따뜻"이 아니다
        ([50], [0]),  # 하루뿐
    ]
    for temperatures, expected in cases:
        assert dailyTemperatures(temperatures) == expected, (temperatures, expected)
    print("모든 케이스 통과")
