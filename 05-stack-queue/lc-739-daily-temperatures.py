# 핵심: 단조 스택 — 아직 답을 못 받은 인덱스를 줄에 세워두고, 새 값이 오면 조건에 걸리는
#       사람들을 내보내며 `지금 - 그때`를 적는다. 주식가격과 부등호만 반대(더 큰 값을 찾는다).
#       못 찾으면 답이 0이라 answer를 [0]*n 으로 시작하면 마무리 루프 자체가 필요 없다.
# 리뷰: 자력 통과. 주식가격(1단) 직후에 풀어 "부등호만 바꾸면 되네"를 직접 확인한 것이 목적.
#       [70,70,70] → [0,0,0] 케이스로 < 와 <= 구분도 확인됨 (같은 기온은 '더 따뜻'이 아니다).
