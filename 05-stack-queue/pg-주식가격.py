# 문제: https://school.programmers.co.kr/learn/courses/30/lessons/42584
# 핵심: 각 시각 i의 답 = "i 뒤에서 처음으로 prices[i]보다 싼 가격이 나오는 시각 j"까지의 거리
#       (j - i). 끝까지 안 싸지면 마지막 시각까지의 거리(n-1-i). 같은 가격은 '떨어진 것'이 아님.
# 리뷰: 20분 자력 통과 — 이중 루프(i마다 뒤를 훑고 싸지면 break). O(n²)라 가격이 계속 오르는
#       입력(n=10만)이면 break가 안 걸려 ~50억 비교 → 프로그래머스는 통과했지만 실전 채점기 위험.
#       09/13 스택 재풀이: 설명을 "보고" 풀었다 — 직접 만들어본 적이 없어 기억에 없었음.
#       같은 날 사다리 2단(lc-739)을 이어서 풀어 패턴으로 묶음. [재풀이: 09/20 — 이번엔 백지로]
#
# ═══════════════════════════════════════════════════════════════════════════════
# 스택 풀이 이해하기 — "줄 서기" 이야기
# ═══════════════════════════════════════════════════════════════════════════════
#
# ■ 발상: 방향을 뒤집는다
#   이중 루프는 "과거가 자기 미래를 직접 뒤지러" 간다.
#   스택 풀이는 반대다 — "미래가 도착하면, 과거에게 너 지금 떨어졌다고 알려준다".
#
# ■ 설정
#   시각마다 사람이 한 명씩 온다. 0초 사람, 1초 사람, 2초 사람 …
#   각자 자기 시각의 "가격표"를 들고 있다.
#   줄이 하나 있고, 줄에 서 있다 = "아직 내 가격이 떨어지는 순간을 못 만났다"(답을 못 받음).
#
# ■ 새 사람이 도착하면 딱 두 가지를 한다
#   ① 줄 맨 뒤 사람에게 묻는다 — "당신 가격표가 내 가격보다 높나요?"
#        높다   → 그 사람은 지금 떨어진 것. 답을 적어주고 줄에서 내보낸다.
#                 그리고 그 앞사람에게 또 묻는다 (여러 명이 연달아 나갈 수 있다)
#        아니다 → 멈춘다 (더 물어볼 필요 없음 — 아래 "왜 멈춰도 되나" 참조)
#   ② 그러고 나서 자기가 줄 맨 뒤에 선다
#
# ■ 답을 적는 방법
#   answer[나가는 사람의 시각] = 지금 시각 - 그 사람의 시각
#   🔴 뺄셈은 "시각끼리". 가격끼리가 아니다.
#      이 문제가 묻는 건 "몇 원 떨어졌나"가 아니라 "몇 초 버텼나"이기 때문.
#
# ■ 손으로 따라가기 — prices = [10, 50, 30, 40, 20], 정답 [4, 1, 2, 1, 0]
#
#   도착        줄 맨 뒤에게 질문        일어난 일                    줄 (시각:가격)
#   ─────────────────────────────────────────────────────────────────────────────
#   0초, 10    줄이 비어있음            그냥 섬                      0:10
#   1초, 50    0:10 > 50 ? 아니오       멈춤, 섬                     0:10, 1:50
#   2초, 30    1:50 > 30 ? 예!          1초 나감 → answer[1]=2-1=1   0:10
#              0:10 > 30 ? 아니오       멈춤, 2초 섬                 0:10, 2:30
#   3초, 40    2:30 > 40 ? 아니오       멈춤, 섬                     0:10, 2:30, 3:40
#   4초, 20    3:40 > 20 ? 예!          3초 나감 → answer[3]=4-3=1   0:10, 2:30
#              2:30 > 20 ? 예!          2초 나감 → answer[2]=4-2=2   0:10
#              0:10 > 20 ? 아니오       멈춤, 4초 섬                 0:10, 4:20
#   끝         줄에 남은 사람 = 끝까지 안 떨어진 사람
#                                       answer[0]=4-0=4, answer[4]=4-4=0
#   → [4, 1, 2, 1, 0]
#
#   4초에 두 명(3초·2초)이 연달아 나간 것에 주목. 그래서 if 가 아니라 while 이다.
#
# ■ 왜 맨 뒤 사람이 안 떨어지면 멈춰도 되나
#   줄은 항상 "앞이 싸고 뒤가 비싼" 상태다. 새 사람이 서기 직전에 자기보다 비싼 사람을
#   전부 내보냈기 때문. (위 표의 줄 상태를 보면 늘 오름차순: 10,50 / 10,30 / 10,30,40 / 10,20)
#   그러니 맨 뒤가 "안 떨어졌다"면 그 앞사람들은 더 싸서 당연히 안 떨어진 것 → 확인 불필요.
#
# ■ 왜 빠른가
#   각 시각 번호가 줄에 한 번 들어가고 한 번 나온다. 전체 작업량이 시각 수의 약 2배 → O(n).
#
# ═══════════════════════════════════════════════════════════════════════════════
# 단조 스택 사다리 — 이 패턴은 한 문제만 봐서는 절대 안 남는다
# ═══════════════════════════════════════════════════════════════════════════════
#
# ■ 한 문장 요약
#   "내 뒤에서 처음으로 [조건]인 값이 나오는 지점을 찾아라" → 단조 스택.
#   아직 답 못 받은 "인덱스"를 줄에 세워두고, 새 값이 오면 조건에 걸리는 사람들을
#   내보내며 `지금 - 그때`를 적는다.
#
# ■ 사다리
#   단  문제                                     앞 단과 다른 점                    결과
#   ─────────────────────────────────────────────────────────────────────────────────────
#   1   주식가격 (이 파일)                        — (더 작은 값 찾기)               09/13 보고 풀이
#   2   LeetCode 739 Daily Temperatures          부등호 반대(더 큰 값) + 못 찾으면 0  09/13 자력 6/6
#                                                 → 마무리 루프가 사라짐
#   3   LeetCode 496 Next Greater Element I      거리가 아니라 "값" + 배열 2개(dict)  09/14 자력 6/6
#   →   3문제 백지 재풀이  09/19(토)              그때가 진짜 측정
#
#   💡 3단이 의미 있었다: 2단은 부등호 하나만 바꾸면 됐지만 3단은 자료구조(dict)가 하나 더
#      붙는데도 막히지 않았다. "같은 코드를 외운 것"이 아니라 "패턴을 옮길 수 있는 상태".
#
# ■ 1단 ↔ 2단 비교 — 부등호 하나 말고는 같다
#     주식가격      : while stack and prices[stack[-1]] > prices[now]
#     Daily Temp.   : while stack and temperatures[stack[-1]] < temperatures[i]
#
# ■ 2026-09-13 기록
#   1단을 "보고서" 풀었다(직접 만들어본 적이 없어 기억에 없었음). 읽어서 이해한 것은
#   기억으로 남지 않는다 — 손으로 만든 것만 남는다. 그래서 같은 문제를 반복하는 대신
#   같은 패턴의 다른 문제(2단)를 바로 이어서 풀어 "유형"으로 묶는 방식으로 전환했다.
#   (BFS가 잘 된 이유도 한 문제를 4번이 아니라 사다리 4문제를 푼 것이었다)
# ═══════════════════════════════════════════════════════════════════════════════


def solution(prices):
    """본 풀이 — 이중 루프. i 뒤를 훑다가 더 싼 가격을 만나면 멈춘다. O(n²)."""
    answer = []
    for i in range(len(prices)):
        count = 0
        for j in range(i + 1, len(prices)):
            count += 1  # 떨어지는 그 초도 "버틴 기간"에 포함되므로 비교 전에 센다
            if prices[i] > prices[j]:
                break
        answer.append(count)
    return answer


def solution_stack(prices):
    """스택 풀이 — 위 '줄 서기' 그대로. O(n). (2026-09-13 재풀이)"""
    n = len(prices)
    answer = [0] * n  # 답판 — 시각 수만큼 칸을 미리 만든다
    stack = []  # 줄 — 사람의 "시각 번호"를 넣는다 (가격이 아니다)

    for j in range(n):  # j = 지금 도착한 사람의 시각
        # ① 줄 맨 뒤부터 물어본다. 여러 명이 연달아 나갈 수 있으므로 while
        #    stack and ...    → 줄이 비었는데 맨 뒤를 보면 에러가 나므로 먼저 확인
        #    stack[-1]        → 줄 맨 뒤 사람의 "시각 번호"
        #    prices[stack[-1]] → 그 사람의 가격표
        while stack and prices[stack[-1]] > prices[j]:
            front = stack.pop()  # 그 사람 줄에서 나감
            answer[front] = j - front  # 답판에 기록 (시각 - 시각)

        # ② 나는 줄 맨 뒤에 선다
        stack.append(j)

    # 끝. 줄에 남은 사람들은 끝까지 안 떨어진 사람 → 마지막 시각까지 버틴 것
    for time in stack:
        answer[time] = (n - 1) - time

    return answer


if __name__ == "__main__":
    cases = [
        ([1, 2, 3, 2, 3], [4, 3, 1, 1, 0]),  # 공식 예제
        ([10, 50, 30, 40, 20], [4, 1, 2, 1, 0]),  # 위 설명에서 손으로 따라간 예제
        ([5, 4, 3, 2, 1], [1, 1, 1, 1, 0]),  # 매초 떨어지는 경우
        ([1, 1, 1], [2, 1, 0]),  # 같은 가격 = 떨어진 게 아님
        ([1, 2, 3, 4, 5], [4, 3, 2, 1, 0]),  # 계속 오름 — 이중 루프의 최악 케이스
        ([1], [0]),  # 시각 1개
    ]
    for prices, expected in cases:
        assert solution(prices) == expected, ("이중 루프", prices, expected)
        assert solution_stack(prices) == expected, ("스택", prices, expected)
    print("모든 케이스 통과 (이중 루프 + 스택)")
