# ■ 문제 요약
#   초 단위로 기록된 주식가격 배열 prices 가 주어진다.
#   각 시점에서 "가격이 떨어지지 않은 기간"이 몇 초인지 배열로 반환한다.
#
#   예: prices = [1, 2, 3, 2, 3]  →  [4, 3, 1, 1, 0]
#
#     1초 시점 가격 1 : 2·3·4·5초 동안 한 번도 떨어지지 않음        → 4초
#     2초 시점 가격 2 : 3·4·5초 동안 떨어지지 않음                  → 3초
#     3초 시점 가격 3 : 4초에 2로 떨어짐. 그 1초는 센다              → 1초
#     4초 시점 가격 2 : 5초에 3으로 올랐으므로 끝까지 유지           → 1초
#     5초 시점        : 뒤가 없다                                   → 0초
#
# ■ 🔴 함정 — "떨어지지 않은" 은 "오른" 이 아니다
#   가격이 같아도(==) 떨어진 게 아니므로 기간은 계속 이어진다.
#   아래 테스트 케이스 4번이 이걸 잡는 장치다.
#
# ■ 제약 조건 (여기에 설계 힌트가 들어 있다)
#   prices 길이 : 2 ~ 100,000
#   각 가격      : 1 ~ 10,000
#   → 길이가 10만이다. 이 숫자를 보고 무엇을 피해야 하는지 먼저 판단한다.
#
# ■ 막히면
#   20분이 지나면 pg-주식가격.py 를 연다. 그전에는 열지 않는다.
#   먼저 종이에 [1, 2, 3, 2, 3] 을 적고 손으로 추적해 본다.
#
# ⏱ 목표 20분
# ─────────────────────────────────────────────────────────────────────


def solution(prices):
    l = len(prices)
    answer = [0] * l

    stack = []

    for j in range(l):
        while stack and prices[stack[-1]] > prices[j]:
            front = stack.pop()
            answer[front] = j - front

        stack.append(j)

    for time in stack:
        answer[time] = (l - 1) - time

    return answer


if __name__ == "__main__":
    cases = [
        ([1, 2, 3, 2, 3], [4, 3, 1, 1, 0]),  # 공식 예제
        ([1, 2, 3, 4, 5], [4, 3, 2, 1, 0]),  # 계속 오름 — 아무도 떨어지지 않음
        ([5, 4, 3, 2, 1], [1, 1, 1, 1, 0]),  # 계속 내림 — 전부 1초 뒤에 떨어짐
        ([3, 3, 3, 3], [3, 2, 1, 0]),  # 🔴 전부 같은 값 — 같으면 유지된다
        ([1, 2], [1, 0]),  # 최소 길이
        ([3, 1, 2, 4], [1, 2, 1, 0]),  # 떨어졌다 다시 오름
        ([5, 1, 1, 5, 3], [1, 3, 2, 1, 0]),  # 🔴 같은 값 + V자가 섞임
    ]
    for prices, expected in cases:
        got = solution(prices)
        assert got == expected, f"prices={prices}  기대={expected}  실제={got}"
    print("모든 케이스 통과")


