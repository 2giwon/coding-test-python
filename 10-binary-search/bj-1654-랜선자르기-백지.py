if __name__ == "__main__":
    import time

    cases = [
        ("공식 예제", 4, 11, [802, 743, 457, 539], 200),
        ("최소 입력", 1, 1, [1], 1),
        ("딱 나누어떨어짐", 1, 10, [10], 1),
        ("자르지 않고 그대로", 1, 1, [100], 100),
        ("길이가 2³¹-1", 1, 1, [2147483647], 2147483647),
        ("n == k", 3, 3, [5, 5, 5], 5),
        ("나눗셈 버림", 2, 3, [7, 7], 3),
        ("같은 길이 3개", 3, 3, [9, 9, 9], 9),
        ("n 이 아주 큼", 2, 1000000, [1000000, 1000000], 2),
        ("길이가 서로 다름", 3, 4, [10, 20, 30], 10),
        ("1cm 랜선 섞임", 4, 5, [1, 1, 100, 100], 33),
        ("n 이 k 보다 훨씬 큼", 2, 7, [100, 50], 20),
        ("k==n, 길이 다름", 3, 3, [10, 20, 30], 15),
        ("k==n, 한쪽만 아주 김", 2, 2, [1, 100], 50),
        ("k==n, 첫 원소가 가장 김", 3, 3, [300, 1, 1], 100),
        ("k==n, 1개로 몰림", 4, 4, [7, 7, 7, 1000], 250),
        ("k==n==1 인데 잘라야 함", 1, 1, [7], 7),
        ("답 후보가 몇 개 안 됨", 2, 3, [4, 5], 2),
    ]

    passed = 0
    print("① 정확성")
    for name, k, n, lines, expected in cases:
        got = solution(k, n, list(lines))
        ok = got == expected
        if ok:
            passed += 1
        mark = "🟢" if ok else "🔴"
        print(f"  {mark} {name:<24} k={k:<6} n={n:<9} 기대={expected:,}")
        if not ok:
            print(f"  {'':>3}{'':<24} {'':<8} {'':<11} 실제={got}")
    print(f"  → {passed}/{len(cases)} 통과")

    print("\n② 효율성 (제약 최대치 — 멈추지 않으면 Ctrl+C)")
