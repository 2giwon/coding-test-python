# ④ 이제 코드
# ══════════════════════════════════════════════════════════════════════
#
#   아래 테스트 12개가 틀린 것을 잡아준다. **왜 틀렸는지는 직접 찾는다.**
#   테스트 기댓값은 전부 실측 검증된 값이니, 틀리면 테스트가 아니라 코드가 틀린 것이다.
#
#   🔴 힌트·뼈대는 이 파일에 넣지 않는다 (2026-10-22 결정).
#      시간이 넘거나 도저히 안 풀릴 때 **직접 요청**한다. 그때 만들어 준다.
#      이유: 10/21 문자열 압축을 뼈대 빈칸 채우기로 통과했고 "자력 아님"으로
#            기록해야 했다. 빈칸 채우기는 도구를 쓰는 연습이 아니다.
#
# ─────────────────────────────────────────────────────────────────────


def cut_count(lines, length):
    """길이 length 로 잘랐을 때 나오는 랜선 개수."""
    count = 0
    if length == 0:
        return 0
    for line in lines:
        count += line // length

    return count

def solution(k, n, lines):
    """만들 수 있는 랜선의 최대 길이를 반환한다.


    k     : 가지고 있는 랜선 개수
    n     : 만들어야 하는 랜선 개수
    lines : 각 랜선의 길이 리스트 (길이 k)
    """
    # 여기에 작성
    if k == n:
        return lines[0]

    lo, hi = 0, max(lines)
    answer = 0

    while lo < hi:
        mid = (lo + hi) // 2
        if cut_count(lines, mid) >= n:
            answer = mid
            lo = mid + 1
        else:
            hi = mid

    return answer


# ═════════════════════════════════════════════════════════════════════
# ⑤ 정답 2가지 — 🔴 위 solution(내가 쓴 것)은 지우지 않는다. 비교 기준이다
# ═════════════════════════════════════════════════════════════════════
#
#   내 코드와 다른 곳은 4군데다:
#     1. `if k == n: return lines[0]`  → 삭제
#        k == n 이어도 자르면 더 길어질 수 있다. lines[0] 은 그냥 첫 원소라 근거가 없다
#     2. `lo = 0` → `lo = 1`
#        길이 0 은 답이 될 수 없다. 이러면 cut_count 의 `if length == 0` 방어도 불필요
#     3. `while lo < hi` → `while lo <= hi`   🔴 핵심
#        lo == hi 는 "범위에 한 칸 남음"이다. 그 한 칸을 안 보고 끝냈다
#     4. `hi = mid` → `hi = mid - 1`
#        mid 는 이미 ❌ 판정이 났다. 범위에 남겨둘 이유가 없다
#
#   🔴 두 형태를 섞으면 틀린다 — 내 코드는 B형 루프 조건(lo < hi)에
#      A형 mid 계산((lo+hi)//2)을 썼다. 각각은 맞는데 조합이 안 맞았다.
#
#        A 닫힌 구간형  : while lo <= hi  +  hi = mid - 1  →  answer 변수가 답
#        B 반열린 구간형 : while lo <  hi  +  mid 를 위로 편향  →  lo 가 답
#
# ─────────────────────────────────────────────────────────────────────


def cut_count_ref(lines, length):
    """정답 풀이용 개수 세기 (length >= 1 을 전제하므로 0 방어가 없다)."""
    return sum(x // length for x in lines)


def solution_ref_a(k, n, lines):
    """정답 A — 닫힌 구간형(표준형). 이 형태를 기본으로 외우는 것을 권한다."""
    lo, hi = 1, max(lines)
    answer = 0
    while lo <= hi:
        mid = (lo + hi) // 2
        if cut_count_ref(lines, mid) >= n:
            answer = mid  # 성공한 길이를 기억해 둔다
            lo = mid + 1  # 더 긴 쪽도 되는지 보러 간다
        else:
            hi = mid - 1  # 너무 길다. mid 는 버린다
    return answer


def solution_ref_b(k, n, lines):
    """정답 B — 반열린 구간형. 내가 쓰려던 `while lo < hi` 를 올바르게 고친 것.

    🔴 `mid = (lo + hi + 1) // 2` 의 +1 이 핵심이다. 없으면 무한 반복에 빠진다.
       lo=4, hi=5 일 때 mid=(4+5)//2=4 이고, 성공하면 lo=4 → 아무것도 변하지 않는다.
       +1 을 붙이면 mid=5 가 되어 진행한다.
       ("마지막 성공을 찾을 때는 mid 를 위로 편향" — lo=4, hi=5 를 손으로 넣어보면 보인다)
    """
    lo, hi = 1, max(lines)
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if cut_count_ref(lines, mid) >= n:
            lo = mid  # mid 는 성공했으니 버리지 않는다
        else:
            hi = mid - 1
    return lo  # answer 변수가 필요 없다


