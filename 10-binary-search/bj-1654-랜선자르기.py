#   오늘은 측정일이 아니라 학습일이다. 처음 쓰는 도구이니 설명을 먼저 읽는다.
#
# ═════════════════════════════════════════════════════════════════════
# ① 문제
# ═════════════════════════════════════════════════════════════════════
#
#   랜선 K개를 가지고 있고, 각각의 길이가 주어진다.
#   이것을 잘라서 **길이가 모두 똑같은 랜선 N개 이상**을 만들어야 한다.
#
#   - 자를 때 손실은 없다. 길이 802 를 200 씩 자르면 200 이 4개 나오고 2 가 남는다
#     (남는 2 는 버린다 — N개를 만드는 데 쓸 수 없다)
#   - 1cm 단위로만 자른다. 즉 **답은 정수**다
#   - 자르지 않고 그대로 쓸 수도 있다
#
#   구할 것: 만들 수 있는 랜선의 **최대 길이**
#
#   예) K=4, N=11, 길이 = [802, 743, 457, 539]  →  답 200
#
#     길이 200 으로 자르면:
#        802 → 4개 (802 // 200)     남는 2 버림
#        743 → 3개                  남는 143 버림
#        457 → 2개                  남는 57 버림
#        539 → 2개                  남는 139 버림
#        합계 11개  →  N=11 을 만족 ✅
#
#     길이 201 로는:
#        802→3  743→3  457→2  539→2  = 10개  →  11개가 안 된다 ❌
#
#     200 은 되고 201 은 안 된다 → **200 이 최대 길이**
#
# ─────────────────────────────────────────────────────────────────────
# ② 멈추고 한 줄만 (채점하지 않는다. 틀려도 그냥 지나간다)
#
#   떠오르는 자료구조 / 알고리즘 : 완전 탐색
#   그렇게 생각한 이유         : 최소공배수를 구해서 그걸로 자른다음 총 갯수(N)을
#                              구해서 주어진 N 값과 다르면 최소공배수의 다음 값으로
#                              계산해서 확인
#
#   ■ 확인 결과 (2026-10-22, 전부 실측)
#
#     🟢 맞은 것 — "길이를 정해 → 개수를 세어 → 확인한다" 이 구조가 정확하다.
#        ③-2 의 조건 1(어려운 질문을 쉬운 판정으로 바꾸기)을 스스로 찾았다.
#        이 유형에서 어려운 부분이 이것이고, 반으로 접기는 기계적인 틀이다.
#        "완전 탐색"도 ③-1 방법 1 과 같다 — 틀린 게 아니라 느린 방법이다.
#
#     🔴 최소공배수 — 방향이 반대다
#        [802,743,457,539] 의 최소공배수 = 146,780,427,178 (12자리).
#        가장 긴 랜선(802)보다 1억 8,301만 배 크다 → 그 길이로 자르면 **0개**.
#        "다음 값"으로 가면 더 커지니 더 안 나온다.
#
#        왜 떠올랐나: "길이가 모두 똑같은" 을 "나누어떨어져야 한다"로 읽었다.
#        🔴 그런데 지문에 "남는 건 버린다"가 있다 → 나누어떨어질 필요가 없다.
#        증거: 정답 200 에서 802%200=2, 743%200=143, 457%200=57, 539%200=139
#              — **네 개 중 하나도 나누어떨어지지 않는데 그게 정답이다.**
#        → 최소공배수는 없는 제약을 푸는 도구였다.
#
#     🔴 "N 값과 다르면" — 여기가 틀렸다
#        딱 N개가 아니라 **N개 이상이면 성공**이다.
#        실측: '딱 N개' 로 풀면 아래 테스트 10개 중 **3개가 틀린다**
#              (나눗셈 버림 / 길이가 서로 다름 / 1cm 랜선 섞임 — 전부 "답 없음")
#
#        [7,7], N=3 을 전부 펼치면:
#            길이 1: 14개 ✅   길이 2: 6개 ✅   길이 3: 4개 ✅ ← 정답
#            길이 4:  2개 ❌   길이 5: 2개 ❌   ...
#        🔴 "정확히 3개"가 되는 길이가 **하나도 없다.** 정답 길이 3 은 4개가 나온다.
#        🟡 공식 예제는 우연히 맞는다 — 정확히 11개인 길이가 186~200 으로 15개
#           있고 그 최댓값이 200 이라서. **예제만 보면 안 보이는 버그다.**
#
#   ↓ 적었으면 아래로. ③ 이 이 파일의 본문이다
#
# ═════════════════════════════════════════════════════════════════════
# ③-1  🔴 왜 다른 방법은 안 되나 — 하나씩
# ═════════════════════════════════════════════════════════════════════
#
#   먼저 알아둘 수: 길이는 최대 **2,147,483,647**(약 21억), 랜선은 최대 **1만 개**다.
#   컴퓨터는 1초에 대략 **1억 번** 계산한다. 이 두 숫자를 계속 쓴다.
#
# ──────────────────────────────────────────────────
#   ❌ 방법 1 — 완전탐색 (1부터 하나씩 올려보기)
# ──────────────────────────────────────────────────
#   생각: 길이 1 로 해보고, 2 로 해보고, 3 으로 해보고... 마지막으로 성공한 길이가 답.
#
#   🟢 이 방법은 **답이 맞다.** 논리에 구멍이 없다.
#   🔴 문제는 속도다:
#        반복 횟수      : 최악 21억 번 (길이 1 ~ 21억)
#        한 번마다 비용 : 랜선 1만 개를 전부 나눠봐야 한다 → 1만 번
#        총             : 21억 × 1만 = **21조 번**
#        1초에 1억 번이면 → 약 **58시간**
#
#   → 그래서 못 쓴다. **"틀렸다"가 아니라 "안 끝난다"** 다. 이 구분이 중요하다.
#     (실제로 이 방법은 작은 입력에서 **검산용**으로 쓸 수 있다.
#      아래 테스트의 기댓값 12개는 이 방법과 대조해서 검증했다 — 18,391건 불일치 0)
#
# ──────────────────────────────────────────────────
#   ❌ 방법 2 — 정렬
# ──────────────────────────────────────────────────
#   생각: 길이를 정렬해 놓으면 뭔가 보이지 않을까?
#
#   🔴 정렬은 **데이터의 순서를 바꾸는** 도구다. 그런데 이 문제의 답(200)은
#      **데이터 안에 없다.** [802, 743, 457, 539] 를 어떻게 정렬해도 200 은 안 나온다.
#
#   → 정렬이 **느려서** 탈락한 게 아니다. 1만 개 정렬은 0.001초다.
#     **쓸 데가 없어서** 탈락이다. 🔴 탈락 이유가 방법 1 과 종류가 다르다.
#
#     이 구분을 기억해 두면 좋다:
#        (가) 답은 맞는데 **안 끝난다**     → 방법 1
#        (나) 빠른데 **답과 무관하다**       → 방법 2
#
# ──────────────────────────────────────────────────
#   ❌ 방법 3 — 그리디 (긴 랜선부터 자른다 같은 전략)
# ──────────────────────────────────────────────────
#   생각: 긴 것부터 유리하게 자르면 더 많이 나오지 않을까?
#
#   🔴 그리디는 "**선택**을 순서대로 하는" 도구다. 그런데 이 문제에는 **선택이 없다.**
#      길이를 200 으로 정하는 순간, 각 랜선에서 몇 개가 나오는지는
#      **나눗셈으로 자동 결정**된다. 802 는 무조건 4개다. 더 잘 자를 방법이 없다.
#
#   → 고를 게 없으면 그리디가 할 일이 없다.
#     🟡 (10/20 드릴 5번 입국심사에서 "그리디"라고 답한 지점이 여기다.
#         그 문제도 같다 — 시간을 정하면 각 심사관이 몇 명 보는지는 자동이다)
#
# ──────────────────────────────────────────────────
#   ❌ 방법 4 — 힙 (heapq)
# ──────────────────────────────────────────────────
#   생각: 10/13 더 맵게처럼 가장 작은 걸 꺼내서 뭔가 하면?
#
#   🔴 힙은 "**가장 작은/큰 것을 반복해서 꺼내고 다시 넣어야** 할 때" 쓴다.
#      더 맵게는 꺼내고 → 섞고 → **다시 넣는** 게 계속 반복됐다.
#      이 문제는 한 번 길이를 정하면 전부 나눗셈 한 번씩이고 **끝**이다.
#      꺼낼 것도, 다시 넣을 것도 없다.
#
# ══════════════════════════════════════════════════════════════════════
# ③-2  🟢 왜 이진탐색인가 — 조건이 딱 두 개다
# ══════════════════════════════════════════════════════════════════════
#
#   이 유형의 정식 이름은 **파라메트릭 서치**(parametric search)다. 풀어쓰면
#   **"답을 직접 구하는 대신, 답을 하나 찍어서 가능한지 물어보고 범위를 좁히는 방법"** 이다.
#
#   쓸 수 있는 조건이 둘 있고, **둘 다** 만족해야 한다. 이 문제는 둘 다 만족한다.
#
# ──────────────────────────────────────────────────
#   조건 1. 답을 하나 정하면 **가능한지 쉽게 판정**할 수 있다
# ──────────────────────────────────────────────────
#   길이를 200 으로 정해 보자.
#        802//200=4  743//200=3  457//200=2  539//200=2  →  합 11개
#        N=11 이상이니 **가능** ✅
#
#   판정 비용: 랜선 1만 개 나눗셈 = 1만 번. 아주 싸다.
#
#   🔴 **이게 이 유형의 핵심 전환이다:**
#
#        원래 질문  "최대 길이를 구하라"        ← 어렵다. 공식이 없다
#        바꾼 질문  "길이 200 이 가능한가?"      ← 쉽다. 나눗셈 1만 번
#
#      어려운 질문 하나를 **쉬운 질문 여러 개**로 바꾼 것이다.
#      여러 개여도 아래 조건 2 때문에 31개면 끝난다.
#
# ──────────────────────────────────────────────────
#   조건 2. 답을 키우면 결과가 **한 방향으로만** 변한다 (단조성)
# ──────────────────────────────────────────────────
#   공식 예제에서 길이를 1 씩 올려보면:
#
#        길이 :  198   199   200   201   202   203  ...
#        개수 :   11    11    11    10    10    10
#        가능?:   ✅    ✅    ✅    ❌    ❌    ❌
#
#   🟢 보이는 게 두 가지다:
#      · 길이를 늘리면 개수는 **줄기만 한다.** 늘어나는 일은 절대 없다
#        (길게 자르면 적게 나온다 — 당연하다. 이 "당연함"이 조건 2 다)
#      · 그래서 ✅ 와 ❌ 가 **✅✅✅❌❌❌ 로 깔끔하게 두 덩어리**다. 섞이지 않는다
#
#   🔴 그래서 중간 하나만 찍어보면 **절반을 통째로 버릴 수 있다:**
#        200 을 찍었더니 ✅  → 200 **아래는 전부 ✅ 가 확실하다.** 볼 필요 없다.
#                              답은 200 이거나 그보다 크다 → 위쪽만 본다
#        201 을 찍었더니 ❌  → 201 **위는 전부 ❌ 다.** 버린다 → 아래쪽만 본다
#
#   🔴 **조건 2 가 없으면 이 방법을 못 쓴다.** 만약 ✅❌✅❌ 처럼 섞여 있으면
#      "버린 절반에 답이 있을 수 있어서" 절반을 버릴 근거가 사라진다.
#      → 새 문제에서 이 유형인지 확인할 때 **반드시 이것부터 따져본다.**
#
# ──────────────────────────────────────────────────
#   그래서 21억이 31번이 된다
# ──────────────────────────────────────────────────
#        21억 → 10억 → 5억 → 2.5억 → 1.2억 → ... → 1
#        반으로 접기를 **31번** 하면 끝난다 (2³¹ ≈ 21억)
#
#        총 비용 : 31번 × 1만 = **31만 번**  → 0.003초 (아래 테스트 실측 9.5ms)
#
#        방법 1 : 21조 번   (58시간)
#        이진탐색: 31만 번  (0.003초)
#        🔴 약 **6,900만 배** 차이. 같은 문제, 같은 답.
#
# ══════════════════════════════════════════════════════════════════════
# ③-3  알고리즘 대략 설명 (코드가 아니라 말로)
# ══════════════════════════════════════════════════════════════════════
#
#   먼저 "판정"만 따로 떼어 함수 하나로 만든다:
#
#       cut_count(lines, length)  →  "그 길이로 자르면 몇 개 나오나"
#       (각 랜선을 length 로 나눈 몫을 전부 더하면 끝이다)
#
#   그리고 범위를 좁히는 틀:
#
#       찾는 범위를 [1, 가장 긴 랜선] 으로 둔다
#       범위가 남아 있는 동안 반복:
#           중간 길이를 하나 고른다
#           cut_count 로 개수를 센다
#           N개 **이상**이면 → 성공. 이 길이를 기억해 두고, 더 긴 쪽으로 좁힌다
#           N개 미만이면    → 실패. 더 짧은 쪽으로 좁힌다
#       마지막으로 성공한 길이가 답
#
#   🟡 함수를 둘로 나누는 이유 — 어제(10/21) 문자열 압축에서 막혔던 그 지점이다.
#      "개수 세기"와 "범위 좁히기"를 한 함수에 넣으면 머리가 두 가지를 동시에
#      따라가야 한다. 떼어놓으면 각각은 아주 짧다.
#
# ══════════════════════════════════════════════════════════════════════
# ③-4  제약 조건 — 위 판단이 맞는지 **검산**용
# ══════════════════════════════════════════════════════════════════════
#
#       K (가지고 있는 랜선 개수)  : 1 ~ 10,000
#       N (만들어야 하는 랜선 개수) : 1 ~ 1,000,000
#       각 랜선의 길이             : 1 ~ 2,147,483,647   (= 2³¹ - 1, 약 21억)
#
#   🟡 제약 숫자는 **도구를 골라주지 않는다. 후보를 줄여줄 뿐이다.**
#      여기서 21억은 "방법 1(하나씩 올려보기)은 안 된다"만 알려준다.
#      **이진탐색을 고른 건 ③-2 의 조건 2(단조성)** 다.
#      (10/20 드릴에서 제약 중심으로 판단하라고 적었는데, 8문항 중 제약이
#       도구를 결정한 건 2개뿐이었다. 나머지는 지문의 구조가 결정한다)
#
#   🔴 21억이 "랜선 21억 개"가 아니라 **"길이라는 값"** 이라는 점도 확인해 둔다.
#      개수는 1만뿐이다. 그래서 정렬(1만 개)은 느리지 않다 — 쓸 데가 없을 뿐이다.
#
