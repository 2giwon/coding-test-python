# ■ 문제
#   n 명이 입국심사를 기다리고 있다.
#   각 심사대에는 심사관이 한 명씩 있고, 심사관마다 한 명을 심사하는 데
#   걸리는 시간이 다르다.
#
#   처음에 모든 심사대는 비어 있다.
#   한 심사대는 한 번에 한 명만 심사할 수 있고, 앞사람 심사가 끝나면
#   다음 사람을 받을 수 있다.
#   모든 사람은 반드시 심사를 받아야 한다.
#
#   심사를 기다리는 사람 수 n 과, 각 심사관이 한 명을 심사하는 데 걸리는
#   시간이 담긴 배열 times 가 주어질 때,
#   **모든 사람이 심사를 받는 데 걸리는 시간의 최솟값**을 return 하라.
#
#   (사람을 어느 심사대에 보낼지는 자유롭게 정할 수 있다.
#    꼭 비어 있는 심사대로 보내야 하는 것도 아니다 —
#    더 빨리 끝날 것 같으면 사람이 있는 심사대 뒤에 줄을 세워도 된다)
#
# ■ 공식 예제
#   n = 6,  times = [7, 10]   →   return 28
#
#   7분 걸리는 심사관이 4명을 심사하고 (28분),
#   10분 걸리는 심사관이 2명을 심사하면 (20분),
#   28분에 모든 심사가 끝난다. 이보다 빠르게 할 수는 없다.
#
# ■ 제약 조건
#   입국심사를 기다리는 사람 수 n : 1 명 이상 **1,000,000,000 명** 이하
#   각 심사관의 1인 심사 시간     : 1 분 이상 **1,000,000,000 분** 이하
#   심사관 수 (times 의 길이)     : 1 명 이상 100,000 명 이하
#
#   🟡 테스트가 정확성/효율성으로 나뉘는지는 제출 화면에서 확인하면 된다.
#
# ■ 진행 방법
#   ⏱ 목표 25분.
#
#   🔴 **코드를 한 줄도 쓰기 전에** 아래 네 칸을 먼저 채운다.
#      (2단 기록 칸에 "다음에 또 틀릴 지점 ①"로 본인이 적어 둔 것이다)
#
#        lo        = 1
#        hi        = 42 = 최소시간 (7분) * 6
#        루프 조건  = while lo <= hi
#        성공했을 때 = 48 // 2 => mid - 1
#        실패했을 때 = mid + 1
#
#      네 칸을 채운 다음에 solution 을 쓴다. 순서를 바꾸지 않는다.
#
#   🟡 "왜 이 도구인가" 설명은 넣지 않았다. 3단은 설명 없이 꺼내는 단계다.
#      25분이 지나거나 도저히 막히면 그때 말해 주면 힌트를 만들어 준다.
# ─────────────────────────────────────────────────────────────────────

def check_line(n, times, mid):

    total = 0
    for t in times:
        total += mid // t

    return total >= n


def solution(n, times):
    lo, hi = 1, (min(times) * n)
    answer = 0
    while lo <= hi:
        mid = (lo + hi) // 2
        if check_line(n, times, mid):
            answer = mid
            hi = mid - 1
        else:
            lo = mid + 1

    return answer


