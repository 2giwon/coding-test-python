#
#   ③ 판정 함수
#      무엇을 세었는가   : mid 분 동안 각 심사관이 볼 수 있는 사람 수(mid // t)
#                         의 합계를 n 과 비교
#      등호 방향         : 🟢 **자력으로 >= 를 골랐고 맞았다**
#         검증: `>` 로만 바꿔 돌리면 2,000건 중 1,443건 오답.
#         어제 기록에 "또 틀릴 지점 ③ 판정 함수 등호"로 본인이 적어 둔
#         자리인데 도움 없이 넘었다.
#      🔴 발상 자체는 받았다 (위 '요청한 힌트 ②')
