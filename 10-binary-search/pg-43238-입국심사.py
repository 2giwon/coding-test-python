# ■ 코드를 쓰기 전에 적은 것 — 🟢 처음으로 실제로 지켰다
#   (1차 → 3차까지 세 번 고쳤다. 고친 과정 자체가 기록이다)
#
#   1차:  lo = 6 (= 사람 수)      · hi = 최소시간 × 사람 수 · 루프 조건 = (공백)
#         성공 = mid + 1          · 실패 = mid - 1
#   2차:  lo = 상한 ÷ 2           · 루프 조건 = while lo <= hi
#         성공 = mid - 1 / hi = mid   ← 서로 다른 두 틀을 한 줄에 섞어 적었다
#   3차:  lo = 1
#         hi = 최소시간 × 사람 수
#         루프 조건 = while lo <= hi
#         성공했을 때 = hi = mid - 1
#         실패했을 때 = lo = mid + 1
#
#   🔴 코드를 쓰기 전에 네 칸을 적는 절차가 실제로 작동했다.
#      lo 가 두 번 틀렸는데 **코드를 한 줄도 쓰기 전에** 잡혔다.
#      어제(64062)는 같은 종류의 오류 4개가 코드 안에서 서로를 덮고 있었다.
