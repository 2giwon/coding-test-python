# ─────────────────────────────────────────────────────────────────────
# ■ 풀고 나서 적을 것 (2026-10-29 기록)
#   소요 시간      : 🔴 25분 초과 (정확한 값 미기재)
#   요청한 힌트    : 🔴 **받았다 — 자력이 아니다**
#                    ① lo : 두 번 틀린 뒤 "답이 가장 작아질 수 있는 상황은?"
#                            까지 유도받았다 (거의 답)
#                    ② 판정 함수 발상 : 🔴 **전부 받았다**
#                            "28 ÷ 7 = 4명" — 시간을 주면 몇 명 볼 수 있는지는
#                            나눗셈 한 번이라는 것
#   제출 결과      : 🟢 프로그래머스 통과
#
#   ① 경계 처리 — 3전째였다  → 🟢 **자력 통과. 3전 1승**
#      루프 조건                : while lo <= hi  (닫힌 구간형)
#      성공했을 때 양쪽 갱신     : answer = mid ; hi = mid - 1
#      실패했을 때 양쪽 갱신     : lo = mid + 1
#      🔴 `lo == hi` 한 칸을 검사했는가 : 🟢 **예.**
#         1단(bj-1654)·2단(64062)에서 둘 다 놓쳤던 자리를 처음으로 넘겼다.
#         이 항목에는 힌트가 없었다.
#
#   ② 제약을 읽고 무엇을 결정했는가
#      hi 를 무엇으로 잡았는가 : 🟢 **자력** — min(times) × n
#         근거: 가장 빠른 심사관 한 명에게 n 명을 전부 몰아도 끝은 난다.
#         1·2단과 달리 max(배열) 로는 안 되는 자리였는데 첫 시도에 맞혔다.
#         🟡 min 을 고른 효과가 수치로 나왔다 — 판정 함수 호출 44회.
#            max(times) × n 이면 범위가 10만 배 커져 60회쯤 돈다.
#      답이 int 범위를 넘는지 : 최대 1e9 × 1e9 = 1e18. 파이썬 int 는 자리수
#         제한이 없어 그대로 두면 된다.
#      🔴 lo : 두 번 틀렸다. 1차 lo = n (단위가 "명"), 2차 lo = 상한 ÷ 2.
