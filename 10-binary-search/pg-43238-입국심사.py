# ■ 채점 — 기댓값은 전부 완전탐색으로 실측한 값이다 (2026-10-29)
#
#   오라클: "다음 사람은 가장 빨리 비는 심사대로 간다"를 힙으로 그대로
#           시뮬레이션해서 끝나는 시각을 구했다. 이진탐색을 쓰지 않으므로
#           독립적인 기준이 된다. 공식 예제도 28 로 일치했다.
# ─────────────────────────────────────────────────────────────────────
if __name__ == "__main__":
    cases = [
        ("공식 예제", 6, [7, 10], 28),
        ("사람 1명", 1, [7, 10], 7),
        ("심사관 1명", 5, [3], 15),
        ("심사관이 사람보다 많다", 2, [1, 2, 3, 4, 5], 2),
        ("전부 같은 값", 4, [5, 5], 10),
        ("느린 심사관은 안 쓰는 게 낫다", 10, [1, 1000000000], 10),
        ("1 과 큰 값", 7, [1, 100], 7),
        ("세 명이 제각각", 11, [2, 3, 5], 12),
        ("심사관 수 = 사람 수", 4, [4, 9, 2, 7], 6),
        ("같은 값 여러 개", 100, [7, 7, 7], 238),
    ]

    passed = 0
    print("① 정확성")
    for name, n, times, expected in cases:
        got = solution(n, list(times))
        ok = got == expected
        if ok:
            passed += 1
        mark = "🟢" if ok else "🔴"
        print(f"  {mark} {name:<26} n={n:<5} times={str(times):<22} 기대={expected:,}")
        if not ok:
            print(f"  {'':>3}{'':<26} {'':<7} {'':<28} 실제={got}")
    print(f"  → {passed}/{len(cases)} 통과")

    # ── 여기서부터는 제약 최대치다. 사람을 하나씩 세는 풀이면 끝나지 않는다.
    #    멈추지 않으면 Ctrl+C 로 끊고, 그게 바로 "제약을 안 읽었다"는 신호다.
    import time

    big = [
        ("심사관 1명 × 최대치", 1000000000, [1000000000], 10**18),
        ("심사관 10만명 전부 1분", 1000000000, [1] * 100000, 10000),
        ("심사관 10만명 무작위", 1000000000, list(range(1, 100001)), None),
    ]

    print("\n② 효율성 (제약 최대치 — 멈추지 않으면 Ctrl+C)")
    for name, n, times, expected in big:
        t = time.perf_counter()
        got = solution(n, list(times))
        el = (time.perf_counter() - t) * 1000
        if expected is None:
            mark = "🟡"  # 손으로 계산되는 모양이 아니라 시간만 본다
            note = "(기댓값 없음 — 시간만 확인)"
        else:
            mark = "🟢" if got == expected and el < 3000 else "🔴"
            note = f"기대={expected:,}"
        print(f"  {mark} {name:<24} {el:>9.1f}ms  {note:<28} 실제={got:,}")


