    for name, stones, k, expected in cases:
        got = solution(list(stones), k)
        ok = got == expected
        if ok:
            passed += 1
        mark = "🟢" if ok else "🔴"
        print(f"  {mark} {name:<18} k={k:<3} stones={str(stones):<34} 기대={expected:,}")
