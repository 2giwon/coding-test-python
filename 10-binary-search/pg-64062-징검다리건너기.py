# ■ 1차 시도 복원 (2026-10-27) — 2차 풀이를 같은 자리에 쓰면서 지워진 것을 되살렸다
#
#   🟢 로직은 정답이었다 : 로컬 10/10, 오라클 교차검증 2,000건 불일치 0건
#   🔴 복잡도가 틀렸다   : 걸린 시간 = 답 × 배열길이
#                         제약 최대치(답 1억 8천만 × 길이 20만)에서 약 588시간
#
#   def solution(stones, k):
#
#       listStones = list(stones)
#
#       distance = 0
#       answer = 0
#
#       while True:
#           for i in range(len(listStones)):
#
#               stone = listStones[i]
#               if stone <= 0:
#                   distance += 1
#               else:
#                   distance = 0
#
#               if listStones[i] > 0:
#                   listStones[i] -= 1
#
#               if distance >= k:
#                   return answer
#
#           answer += 1
#           distance = 0
#
#   ■ 1차 → 2차 사이에 일어난 일 (이게 오늘의 수확이다)
#     1차는 "1번 사람 → 2번 → 3번…" 으로 **답을 하나씩 세었다.**
#     2차는 "답을 mid 로 찍어 놓고 되는지 물어본다" 로 바꿨다.
#     같은 문제, 같은 판정 함수인데 **답을 세는 것에서 찍는 것으로** 바뀌었다.
#     🔴 그 전환이 매개변수 탐색(답 자체를 이진탐색하기)이다.
# ─────────────────────────────────────────────────────────────────────


def check_distance(stones, count, k):
    distance = 0

    for stone in stones:
        if stone < count:
            distance += 1
            if distance >= k:
                return False
        else:
            distance = 0

    if distance >= k:
        return False

    return True

def solution(stones, k):
    answer = 1

    lo, hi = 1, max(stones)
    while lo <= hi:
        mid = (lo + hi) // 2
        if check_distance(stones, mid, k):       ## 건널 수 있다
            lo = mid + 1
            answer = mid
        else :                                      ## 건널 수 없다
            hi = mid - 1

    return answer



# ─────────────────────────────────────────────────────────────────────
# ■ 참고 정답 (2026-10-27 추가) — 본인 풀이와 비교용. 위 solution 은 건드리지 않았다
#
#   🔴 본인 풀이가 이미 통과했다. 아래는 "더 좋은 답"이 아니라
#      **다른 두 가지 모양**이다. 비교해서 얻을 것만 얻으면 된다.
#
#   판정 함수(can_cross_ref)는 본인이 쓴 check_distance 와 사실상 같다.
#   🟢 배열을 복사하지도, mid 를 빼지도 않는 그 방식이 맞다.
# ─────────────────────────────────────────────────────────────────────


def can_cross_ref(stones, k, x):
    """x 명이 모두 건널 수 있는가. 배열을 한 번만 훑는다."""
    run = 0
    for stone in stones:
        if stone < x:  # x 명이 지나가면 이 돌은 0 이 되어 있다
            run += 1
            if run >= k:  # 0 이 k 개 연속이면 k+1 칸을 뛰어야 한다 → 불가능
                return False
        else:
            run = 0
    return True


def solution_ref_a(stones, k):
    """형태 A — 반열린 구간형. 본인이 쓴 닫힌 구간형과 짝을 이루는 다른 한 형태다.

    닫힌 구간형(본인 풀이):  while lo <= hi / hi = mid - 1 / answer 를 따로 기억
    반열린 구간형(이것)   :  while lo <  hi / hi = mid - 1 / answer 변수가 없다
                           대신 mid 를 올림(+1)으로 구해야 한다
    """
    lo, hi = 1, max(stones)
    while lo < hi:
        mid = (lo + hi + 1) // 2  # 🔴 +1 이 핵심. 없으면 lo = mid 에서 무한 루프
        if can_cross_ref(stones, k, mid):
            lo = mid  # 🔴 mid + 1 이 아니다. mid 자신이 답일 수 있다
        else:
            hi = mid - 1
    return lo


def solution_ref_b(stones, k):
    """형태 B — 🔴 이진탐색을 아예 쓰지 않는 O(n) 풀이.

    이 문제의 답은 결국 **"연속한 k 칸 중 가장 큰 값"들을 모아서 그 중 가장 작은 값**이다.
    (k 칸짜리 창을 왼쪽부터 오른쪽으로 밀면서, 각 창의 최댓값을 본다.
     그 최댓값들 중 최솟값이 답이다 — 그 창이 가장 먼저 막히는 구간이기 때문)

    창의 최댓값을 매번 다시 구하면 O(n·k) 로 느리다. 그래서 덱(양쪽에서 넣고 뺄 수
    있는 줄)에 "값이 큰 순서로" 인덱스를 담아 두고, 창을 한 칸 밀 때마다
    왼쪽에서 벗어난 것을 버리는 식으로 O(n) 에 구한다.
    🟡 이진탐색 연습이 목적이라면 이 풀이는 지금 외우지 않아도 된다.
    """
    from collections import deque

    n = len(stones)
    k = min(k, n)
    dq = deque()  # 값이 큰 순서로 인덱스를 담는다
    answer = None
    for i, v in enumerate(stones):
        while dq and stones[dq[-1]] <= v:
            dq.pop()
        dq.append(i)
        if dq[0] <= i - k:  # 창 왼쪽을 벗어난 인덱스는 버린다
            dq.popleft()
        if i >= k - 1:  # 창이 처음 완성된 순간부터 최솟값을 모은다
            m = stones[dq[0]]
            answer = m if answer is None else min(answer, m)
    return answer


