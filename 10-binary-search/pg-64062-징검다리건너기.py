# ■ 방향 힌트 (2026-10-27, 본인 요청으로 추가 — 코드는 없다)
#
#   1차 시도는 **로직이 맞았다**. 로컬 10/10, 교차검증 2,000건 불일치 0건.
#   틀린 것은 답이 아니라 속도였다. 그 코드는 지우지 말고 위에 그대로 둔다.
#
#   ■ 1차 시도가 한 일
#     "1번 사람을 실제로 건너게 해 본다 → 2번 → 3번 → ..."
#     답을 **1씩 올려 가며 하나하나 세었다.**
#     그래서 걸린 시간 = 답 × 배열길이. 답이 1억 8천만이면 588시간이다.
#
#   🔴 **힌트: 답을 세지 말고, 답을 찍어서 맞는지 물어본다.**
#
#     이진탐색에는 두 가지 쓰임이 있다.
#       ① 정렬된 배열에서 값을 찾기        ← 보통 먼저 배우는 것
#       ② **답 자체를 이진탐색하기**        ← 1단(랜선 자르기)에서 쓴 것
#
#     1단에서 한 일을 떠올려 본다 —
#       "랜선 길이를 x 로 정해 본다 → x 로 잘랐을 때 몇 개 나오나 세어 본다
#        → N개 이상인가? → x 를 늘릴지 줄일지 정한다"
#       길이를 1부터 하나씩 올려 보지 않았다. **정해 놓고 물어봤다.**
#
#   ■ 그래서 이 문제에서 정해 놓고 물어볼 것은 무엇인가
#     1단에서 "구하려는 답"이 랜선 길이였듯이, 여기서 구하려는 답은
#     **건널 수 있는 사람 수**다. 그것을 x 로 정해 놓고 묻는다 —
#
#       🔴 "x 명이 건넌 뒤에도, 다음 사람이 건널 수 있는가?"
#
#     이 질문에 **배열을 한 번만 훑어서** 예/아니오로 답할 수 있으면 끝이다.
#     (x 명이 지나갔다면 각 디딤돌의 숫자가 얼마나 줄어드는지,
#      숫자가 0 이하가 된 디딤돌이 몇 칸 연속으로 생기는지를 보면 된다)
#
#     그리고 이 질문에는 1단과 똑같은 성질이 있다 —
#       x 가 작으면 예, x 가 커지면 어느 지점부터 계속 아니오.
#       그 **경계**가 답이다. 🔴 오늘 재려던 것이 바로 이 경계 처리다.
#
#   ■ 탐색 범위는 어디서 어디까지인가
#     1단에서 hi 를 max(lines) 로 잡았던 것과 같은 자리를 찾아본다.
#
#   ■ 여기까지가 힌트다. 아래는 직접 채운다
#     · x 가 정해졌을 때 "건널 수 있는가"를 어떻게 한 번에 판정할 것인가
#     · lo / hi 의 초깃값
#     · while 조건과, 예일 때 / 아니오일 때 각각 어디를 버릴 것인가
#     · 🔴 마지막 한 칸(lo == hi)이 검사되는가 — 1단에서 무너진 그 지점
#
