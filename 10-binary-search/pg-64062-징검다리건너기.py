# ■ 문제
#   징검다리가 일렬로 놓여 있고, 디딤돌마다 숫자가 하나씩 적혀 있다.
#   한 사람이 디딤돌을 밟으면 그 디딤돌의 숫자가 1 줄어든다.
#   숫자가 0 이 된 디딤돌은 밟을 수 없다.
#
#   사람들은 한 명씩 차례로 건넌다 (앞사람이 다 건너야 다음 사람이 출발).
#   건널 때 규칙:
#     · 밟을 수 있는 디딤돌 중 **가장 가까운 것으로만** 이동한다
#     · 0 이 된 디딤돌은 뛰어넘을 수 있지만, 한 번에 건너뛸 수 있는
#       칸 수는 최대 k 칸이다 (출발지점과 도착지점도 칸 수에 포함된다)
#
#   디딤돌 숫자 배열 stones 와 최대 건너뛰기 칸 수 k 가 주어질 때,
#   최대 몇 명이 건널 수 있는지 return 하라.
#
# ■ 공식 예제
#   stones = [2, 4, 5, 3, 2, 1, 4, 2, 5, 1],  k = 3   →   return 3
#
#   네 번째 사람은 세 번째 디딤돌에서 일곱 번째 디딤돌로 가야 하는데
#   그 사이 네 칸을 건너뛰어야 한다. k = 3 이라 불가능하다. 그래서 3명.
#
# ■ 제약 조건
#   stones 의 길이  : 1 이상 200,000 이하
#   stones 의 각 원소: 1 이상 200,000,000 이하의 자연수
#   k               : 1 이상 stones 의 길이 이하의 자연수
#   건너야 하는 사람 수에는 제한이 없다
#   🔴 정확성 테스트와 **효율성 테스트가 따로 채점된다**
#
# ■ 진행 방법
#   ⏱ 목표 25분. (1단은 20분 목표에서 초과했으므로 2단은 넉넉히 잡았다)
#   25분이 지나거나 도저히 막히면 **그때 말해 주면** 힌트를 만들어 준다.
#
#   🟡 이번에는 "왜 이 도구인가" 설명을 일부러 넣지 않았다.
#      1단에서 그 설명을 읽고 풀었으니, 2단은 설명 없이 도구를 꺼내 보는
