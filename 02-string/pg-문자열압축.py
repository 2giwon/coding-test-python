# 상태: 🟡 문자열 1단 — 새 유형 첫 문제 (2026-10-20)
#
# ─────────────────────────────────────────────────────────────────────
# ■ 이 문제의 위치
#   문자열(string) 유형의 입문 문제다. 2020 카카오 블라인드 실제 출제.
#   `02-string/` 폴더의 첫 문제다 — 미착수 유형 4개 중 첫 칸을 메운다.
#   새 유형이므로 백지가 아니다 — "도구 설명"은 주고 "풀이"는 주지 않는다.
#
# ■ 문제 요약
#   문자열 s 를 앞에서부터 **1개 이상의 단위**로 잘라, 같은 조각이
#   연속해서 나오면 "반복횟수 + 조각" 으로 바꿔 압축한다.
#   단위 길이를 1부터 끝까지 바꿔가며 시도해서, **가장 짧아진 길이**를 반환한다.
#
#   🔴 자르는 단위는 문자열 **맨 앞부터 일정한 길이**로만 가능하다.
#      중간부터 다른 길이로 바꿔 자르는 것은 안 된다.
#
#   예: s = "aabbaccc"  →  7
#
#     단위 1 : a a b b a c c c
#              → "2a" + "2b" + "a" + "3c"  =  2+2+1+2 = 7  ← 가장 짧다
#     단위 2 : aa bb ac cc
#              → 붙은 조각이 하나도 같지 않다           =  8
#     단위 4 : aabb accc
#              → 같지 않다                              =  8
#
#   예: s = "abcabcabcabcdededededede"  →  14
#
#     단위 6 : abcabc abcabc dedede dedede
#              → "2abcabc" + "2dedede"  =  7+7 = 14
#     (단위 3 으로 하면 16 이라 더 길다 — 단위를 전부 시도해야 하는 이유)
#
# ─────────────────────────────────────────────────────────────────────
# ■ 쓸 도구: 문자열 슬라이싱 (새 자료구조 없음)
#
#   이 유형은 새 알고리즘을 배우는 게 아니다. 이미 아는 것만 쓴다.
#
#   s[i:i+k]            # i 부터 k 글자. 끝을 넘어가도 에러 없이 짧게 잘린다
#   s[i:i+k] == s[j:j+k]  # 두 조각이 같은지
#   len(str(cnt))       # 숫자를 문자로 썼을 때 몇 자리인가  ← 🔴 아래 함정 ④
#   range(1, n)         # 단위 길이를 바꿔가며 시도
#
#   🔴 슬라이싱은 범위를 넘어가도 에러가 나지 않는다.
#      "abc"[2:5] 는 IndexError 가 아니라 "c" 다.
#      편리하지만, 그래서 **꼬리 조각을 빼먹은 것도 에러로 안 알려준다**(함정 ②).
#
# ─────────────────────────────────────────────────────────────────────
# ■ 제약 조건 (🔴 여기에 설계가 들어 있다)
#   s 길이 : 1 ~ 1,000
#   s 는 알파벳 소문자로만 이루어져 있다
#
#   → 길이가 1,000 **뿐**이다.
#     단위 길이 500가지 × 각 단위마다 문자열 1,000글자 훑기 = 50만 번.
#     파이썬에게 아무것도 아니다.
#
#   🔴 이 숫자가 뜻하는 것: **"모든 단위 길이를 다 해봐도 된다"는 허가증**이다.
#     영리한 방법을 찾을 필요가 없다. 10/20 유형식별드릴 8번과 같은 신호다 —
#     제약이 작으면 전탐색이 정답이고, 기법을 꺼내면 틀릴 자리만 늘어난다.
#
# ■ 🔴 함정 5개 — 테스트 케이스가 각각을 잡는다
#   ① 반복 횟수가 1일 때는 숫자를 붙이지 않는다
#      "a" 이지 "1a" 가 아니다. 붙이면 길이가 1 늘어나 답이 커진다.
#   ② 🔴 **마지막에 남는 꼬리 조각**
#      길이가 단위로 딱 나눠떨어지지 않으면 자투리가 남는다.
#      "abcdefg" 를 단위 3 으로 자르면 abc / def / **g** — 이 g 를 빼먹으면
#      답이 7 이 아니라 6 이 된다. 슬라이싱이 에러를 안 내므로 조용히 틀린다.
#   ③ 단위 길이의 범위
#      단위가 len(s) 의 절반을 넘으면 같은 조각이 두 번 나올 수 없다 →
#      압축이 안 되고 원본 길이가 된다. 그래서 답의 **초기값을 len(s) 로 두면**
#      범위를 어디까지 돌리든 안전하다. (길이 1 인 문자열도 이걸로 처리된다)
#   ④ 🔴 **반복 횟수가 10 이상이면 숫자가 두 자리다**
#      "aaaaaaaaaa" (a 10개) → "10a" 는 3글자다. 4글자가 아니다.
#      길이를 셀 때 `+ 1` 로 계산하면 틀린다. `len(str(cnt))` 를 써야 한다.
#      길이 1,000 이면 최대 1,000회 반복 → 네 자리까지 나온다.
#   ⑤ 길이 1 인 문자열
#      압축할 게 없다. 답은 1 이다. (함정 ③ 의 초기값으로 자동 해결된다)
#
# ■ 막히면 — 힌트 사다리 (위에서부터 하나씩만 연다)
#   1단계: 단위 길이를 몇 가지 시도해야 하나? 제약 조건의 1,000 을 보고
#          "전부 해봐도 되는가"를 먼저 판단한다.
#   2단계: 단위 길이를 하나 고정했다고 하자. 문자열을 그 길이로 쭉 잘라
#          나열했을 때, 무엇과 무엇을 비교하면 "반복"을 알 수 있나?
#   3단계: 압축된 문자열을 실제로 만들 필요가 있나?
#          문제가 묻는 것은 **길이**뿐이다. 조각 하나를 내보낼 때
#          길이가 몇 늘어나는지만 더해가면 된다 (🔴 함정 ④ 를 같이 생각할 것).
#
#   20분이 지나면 멈추고 어디까지 갔는지 아래 기록 칸에 적는다.
#
# ⏱ 목표 20분
# ─────────────────────────────────────────────────────────────────────

def compressed_length(s, k):

    count = 1
    first = s[0: k]
    total = 0
    for j in range(k, len(s), k):
        cur = s[j : j + k]
        if first == cur:
            count += 1
        else:
            total += len(first) + (len(str(count)) if count > 1 else 0)
            first = cur
            count = 1

    total += len(first) + (len(str(count)) if count > 1 else 0)
    return total


def solution(s):

    return min(compressed_length(s, k) for k in range(1, len(s) + 1))

if __name__ == "__main__":
    cases = [
        # ── 공식 예제 5개 ──
        ("aabbaccc", 7),  # 단위 1 이 최선
        ("ababcdcdababcdcd", 9),  # 단위 8 → "2ababcdcd"
        ("abcabcdede", 8),  # 🔴 꼬리 "e" 가 답에 포함된다 (함정 ②)
        ("abcabcabcabcdededededede", 14),  # 단위 6 이 최선 (단위 3 은 16)
        ("xababcdcdababcdcd", 17),  # 어떤 단위로도 안 줄어든다
        # ── 함정 케이스 8개 ──
        ("a", 1),  # 🔴 함정 ⑤ 길이 1
        ("ab", 2),  # 반복이 전혀 없음
        ("aa", 2),  # "2a"
        ("aaa", 2),  # "3a"
        ("aaaab", 3),  # "4a" + "b"
        ("abcdefg", 7),  # 🔴 함정 ② 꼬리를 빼먹으면 6 이 나온다
        ("a" * 10, 3),  # 🔴 함정 ④ "10a" 는 3글자다 (4 아님)
        ("a" * 100, 4),  # 🔴 함정 ④ "100a" / "50aa" — 세 자리 숫자
    ]

    for s, expected in cases:
        got = solution(s)
        assert got == expected, f"s={s!r}  기대={expected}  실제={got}"
    print(f"모든 케이스 통과 ({len(cases)}개)")


