#   소요 시간   : 🔴 40분+ (목표 20분 초과)
#   힌트 몇 단  : 🔴 1단 + 2단 + **뼈대 제공**(빈칸 5개 형태로 구조를 받음)
#                 → **자력 아님.** "풀었다"가 아니라 "구조를 받아 빈칸을 채웠다"로 기록한다.
#                   자력으로 적어두면 나중에 "문자열은 됐었는데?"로 잘못 판단한다.
#   프로그래머스 : ✅ 제출 통과 (2026-10-21)
#
#   ■ 🔴 막힌 지점 — 축(axis)을 잘못 잡았다
#     첫 시도 코드가 이랬다:
#         for i in range(len(s)):
#             for j in range(len(s)):
#                 if s[i] == s[i+j]:
#     루프 두 개가 **둘 다 "위치"** 를 훑고, 비교 대상이 **문자 하나**(s[i])였다.
#     → 이 구조는 "단위 1" 하나만 다룬다. **단위 2·3·4... 를 시도하는 축이 없다.**
#     문제가 요구한 것은 "1개 이상 단위로 잘라"인데, 자르는 **단위 자체가 변수**여야 했다.
#     (부수적으로 s[i+j] 는 범위 초과, count + s[i] 는 숫자+문자라 코드가 한 번도 안 돌았다)
#
#   ■ 🟢 풀리게 만든 전환 — 함수 2개로 쪼갰다
#     두 가지를 한 함수에 넣으려다 막혔다:
#         ① 단위 길이를 바꿔가며 시도      → solution()      3줄
#         ② 한 단위에 대해 압축 길이 계산  → compressed_length() 10줄
#     쪼개니 각각은 쉬웠다.
#     🔴 **다음에 막히면 먼저 물어볼 것: "지금 두 가지를 동시에 하려 하나?"**
#        이번 문제에서 가져갈 가장 쓸모 있는 것. 유형 지식이 아니라 재사용 가능한 기술이다.
#
#   ■ 함정 중 실제로 걸린 것 : 🟢 **없음** (①~⑤ 전부 넘김)
#     특히 두 곳이 깨끗했다 —
#       함정 ② 마지막 묶음 확정 : 루프 밖 `total += ...` 를 빼먹지 않았다.
#                                 빼면 13개 중 12개가 틀린다. 슬라이싱이 에러를 안 내서
#                                 **조용히 틀리는** 자리인데 넘겼다.
#       함정 ①④ 한 줄로 동시 처리:
#                                 `len(first) + (len(str(count)) if count > 1 else 0)`
#                                 count==1 → 숫자 생략("a" 이지 "1a" 아님)
#                                 len(str(count)) → a*10 은 "10a"=3, a*100 은 "100a"=4
#
#   ■ 새로 안 것
#     ① 슬라이싱은 범위를 넘어가도 에러가 없다 — s[9:12] → "e".
#        꼬리 조각이 자동으로 짧게 잘려 편하지만, **빼먹어도 에러로 안 알려준다**(함정 ②의 정체)
#     ② 압축 결과 문자열을 만들 필요가 없다. 길이만 더해가면 된다
#     ③ 제약 1,000 = "단위를 전부 시도해도 된다"는 허가증. 영리한 방법을 찾을 필요가 없었다
#     🟡 `range(1, len(s) + 1)` 은 `len(s)//2 + 1` 까지만 돌려도 되지만,
#        전부 돌려도 답이 같고 성능도 문제없다(최악 0.91ms). 고치지 않았다
#
#   ■ 🟢 검증 결과 (2026-10-21 실측) — "채점 통과 ≠ 정답" 패턴이 처음 끊겼다
#     테스트 13개                : 전부 통과
#     무작위 30,000건 교차검증   : 불일치 0건
#                                 (압축 문자열을 실제로 만들어 길이를 재는 **구조가 다른**
#                                  독립 풀이와 대조. 같은 발상으로 두 번 짜면 같은 실수를 반복한다)
#     반복 구조 심은 35건        : 불일치 0건 (단위 1·2·3·5·7 × 반복 2·3·9·10·11·99·100)
#     성능 (제약 최대 1,000자)   : 최악 0.91ms — 10초 제한 대비 1만 배 여유
#     ruff                       : All checks passed
