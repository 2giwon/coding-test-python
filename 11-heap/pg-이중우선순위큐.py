# ─────────────────────────────────────────────────────────────────────
# ■ 이 문제의 위치
#   힙 2단. 1단(더 맵게)에서 "heapq 는 최소 힙뿐"이라고 적어둔 제약에
#   정면으로 부딪히는 문제다. 거기서 배운 게 바로 쓰인다.
#
# ■ 문제 요약
#   operations : 연산 문자열 배열. 세 종류뿐이다.
#
#       "I 숫자"   큐에 그 숫자를 넣는다
#       "D 1"      큐에서 **최댓값**을 삭제한다
#       "D -1"     큐에서 **최솟값**을 삭제한다
#
#   🔴 "D -1" 의 -1 은 숫자가 아니라 "최솟값 쪽"이라는 신호다. 넣는 값과 다르다.
#   🔴 큐가 비어 있는데 D 가 오면 **그 연산은 무시**한다(에러가 아니다).
#
#   반환값: [최댓값, 최솟값]. 큐가 비어 있으면 [0, 0].
#
#   예: ["I 7", "I 5", "I -5", "D -1"]  →  [7, 5]
#
#     I 7    → {7}
#     I 5    → {7, 5}
#     I -5   → {7, 5, -5}
#     D -1   → 최솟값 -5 삭제 → {7, 5}
#     결과   → 최댓값 7, 최솟값 5 → [7, 5]
#
# ─────────────────────────────────────────────────────────────────────
# ■ 1단에서 가져오는 것 + 새로 필요한 것
#
#   이미 아는 것 (더 맵게에서 씀):
#     heapq.heapify / heappop / heappush / h[0] / len(h)
#
#   🔴 새 벽: heapq 는 **가장 작은 것만** 꺼낼 수 있다.
#      이 문제는 가장 큰 것도 꺼내야 한다. 1단 기록 칸에 적어둔 그 제약이다.
#
#      넣을 때 값을 어떻게 바꾸면 "가장 큰 것"이 "가장 작은 것"이 되는지 생각해 본다.
#      (꺼낸 뒤에는 되돌려야 한다는 것도 같이)
#
#   문자열 파싱:
#     op.split()  →  ["I", "7"]  또는  ["D", "-1"]
#     앞쪽이 명령, 뒤쪽이 값 또는 방향이다. 음수 부호가 붙을 수 있다.
#
# ─────────────────────────────────────────────────────────────────────
# ■ 제약 조건
#   operations 길이 : 1 ~ 1,000,000
#   넣는 숫자        : -2,000,000,000 ~ 2,000,000,000
#
#   → 또 100만이다. 연산마다 정렬하거나 `list.remove(max(arr))` 를 쓰면
#     한 번이 O(n) 이라 전체가 100만 × 100만이 된다. 반드시 시간초과다.
#     (아래 테스트의 기준 풀이는 일부러 그 느린 방식으로 적어 뒀다 —
#      답을 맞히는 데는 쓸 수 있지만 제출하면 떨어지는 코드다)
#
# ■ 🔴 함정 4개 — 테스트가 각각을 잡는다
#   ① 빈 큐에서 D : 무시한다. 터지거나 0 을 넣으면 안 된다
#   ② 원소가 `0` 하나만 있을 때 : 답이 [0, 0] 이다.
#      "비어 있을 때"와 **결과가 같아서 값만 보면 구분이 안 된다.**
#      → 비었는지는 값이 아니라 **개수**로 판단해야 한다
#   ③ 🔴 힙을 두 개 쓰면 **둘이 서로 동기화되지 않는다.**
#      한쪽에서 뺀 원소가 다른 쪽에는 그대로 남는다.
#      대부분은 그래도 답이 맞는데, 안 맞는 순간이 하나 있다. 그게 테스트 11번이다
#   ④ 비웠다가 다시 채우는 경우 — ③과 같은 지점이다
#
# ■ 막히면 — 힌트 사다리 (위에서부터 하나씩만 연다)
#   1단: 최솟값용 힙 하나로는 부족하다. 두 번째 힙에는 무엇을 넣을까?
#   2단: 두 힙이 어긋난다. 그런데 "한쪽에서 뺀 원소가 다른 쪽 맨 위"가 되는 건
#        어떤 상황뿐인지 따져 본다 — 그 상황만 막으면 나머지는 저절로 맞는다.
#   3단: "지금 큐에 실제로 몇 개 있는지"를 따로 센다.
#        그 수가 0 이 되는 순간에 해야 할 일이 하나 있다.
#
#   20분이 지나면 멈추고 어디까지 갔는지 아래 기록 칸에 적는다.
#
# ⏱ 목표 20분
# ─────────────────────────────────────────────────────────────────────

import heapq


def solution(operations):

    h = []
    heapq.heapify(h)
    for operation in operations:
        op, num = operation.split()
        if op == "I":
            heapq.heappush(h, int(num))
        if h and op == "D" and num == "1":
            h.remove(max(h))
            heapq.heapify(h)
        if h and op == "D" and num == "-1":
            heapq.heappop(h)

    return [0, 0] if not h else [max(h), min(h)]


# ─────────────────────────────────────────────────────────────────────
# ② 기준 풀이 — 힙 2개 (이 문제가 원래 겨냥한 기술)
#
#   핵심: heapq 는 최소 힙뿐이라 가장 큰 것을 못 꺼낸다.
#         그래서 **부호를 뒤집어 넣은 힙을 하나 더** 둔다.
#         -5 가 -1 보다 작으므로, 뒤집은 힙의 "가장 작은 값" = 원래의 "가장 큰 값".
#         꺼낸 뒤 다시 - 를 붙여 되돌린다.
#
#   🔴 그러면 바로 새 문제가 생긴다 — 두 힙이 서로 모른다.
#      max_h 에서 뺀 원소가 min_h 에는 그대로 남아 있다. 지워줄 방법이 없다
#      (heapq 에는 "중간 원소 삭제"가 없다. remove 를 쓰면 O(n) 이라 쓸 수 없다).
#
#   그런데 대부분은 그래도 답이 맞는다. 왜냐하면:
#      max_h 에서 뺀 원소(= 최댓값)가 min_h 의 맨 위에 오려면
#      그 원소가 **최댓값이면서 동시에 최솟값**이어야 한다 → 원소가 1개뿐일 때만.
#      그리고 그 1개를 빼면 큐는 비어 있다.
#   → 즉 **"비면 양쪽을 확실히 비운다"** 한 가지만 지키면 나머지는 저절로 맞는다.
#      그래서 size 를 따로 세고, 0 이 되는 순간 clear() 한다.
#
#   🔴 clear() 를 빼고 돌려보면 테스트 11번만 틀린다:
#      ["I 3","D 1","I 7","I 1","D -1"]  기대 [7, 7]  →  [7, 3]
#      3 을 D 1 로 뺐지만 max_h 에 -3 이 남아서, 뒤에 min_h 쪽을 지우고 나니
#      최댓값을 묻는 자리에 죽은 3 이 튀어나온다.
#      (무작위 30,000건으로 재보면 335건이 틀린다 — 드문 함정이 아니다)
#
#   값은 못 지우지만 **개수는 셀 수 있다** — 그걸로 넘기는 것이 이 풀이의 요령이다.
# ─────────────────────────────────────────────────────────────────────
def solution_two_heaps(operations):
    min_h = []  # 그대로 넣는 힙   → min_h[0] = 최솟값
    max_h = []  # 부호 뒤집어 넣는 힙 → -max_h[0] = 최댓값
    size = 0  # 🔴 실제로 큐에 몇 개 있는지. 힙 길이는 믿을 수 없다

    for op in operations:
        cmd, num = op.split()
        if cmd == "I":
            n = int(num)
            heapq.heappush(min_h, n)
            heapq.heappush(max_h, -n)
            size += 1
        elif size:  # 빈 큐면 무시 (size 로 판단 — 힙 길이로 보면 틀린다)
            if num == "1":
                heapq.heappop(max_h)  # 최댓값 삭제
            else:
                heapq.heappop(min_h)  # 최솟값 삭제
            size -= 1
            if size == 0:  # 🔴 이 두 줄이 없으면 테스트 11번이 틀린다
                min_h.clear()
                max_h.clear()

    return [0, 0] if size == 0 else [-max_h[0], min_h[0]]


if __name__ == "__main__":
    cases = [
        (["I 16", "D 1"], [0, 0]),  # 공식 예제 1
        (["I 7", "I 5", "I -5", "D -1"], [7, 5]),  # 공식 예제 2
        (["I 1", "I 5", "I 9", "D 1", "D -1"], [5, 5]),
        (["D 1"], [0, 0]),  # 🔴 함정① 빈 큐에서 삭제
        (["D -1", "D 1", "I 42"], [42, 42]),  # 🔴 함정① 두 번 무시한 뒤 삽입
        (["I 5", "D 1", "D -1", "I 3"], [3, 3]),
        (["I 5", "I 5", "D 1"], [5, 5]),  # 중복 값
        (["I -2000000000", "I 2000000000"], [2000000000, -2000000000]),  # 경계값
        (["I 1", "I 2", "D -1", "D -1"], [0, 0]),  # 전부 비움
        (["I 0"], [0, 0]),  # 🔴 함정② 원소가 0 하나 — 빈 큐와 결과가 같다
        (["I 3", "D 1", "I 7", "I 1", "D -1"], [7, 7]),  # 🔴 함정③ 비웠다 다시 채움
        (["I 1", "I 2", "I 3", "D 1", "D 1", "D 1", "D 1"], [0, 0]),  # 남는 D 는 무시
    ]

    for label, fn in [
        ("① 제출본 (remove 방식)", solution),
        ("② 기준 풀이 (힙 2개)", solution_two_heaps),
    ]:
        for operations, expected in cases:
            got = fn(list(operations))
            assert got == expected, f"{label}  operations={operations}  기대={expected}  실제={got}"
        print(f"{label}: {len(cases)}개 전부 통과")
    print("\n🔴 둘 다 정답이지만 속도가 다르다 (연산 100만 기준, 실측)")
    print("   ① remove 방식  : D 1 이 O(n) → 전체 O(n²). 환산 약 37분")
    print("   ② 힙 2개 방식  : 0.17초")


