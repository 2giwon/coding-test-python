#     함정① 빈 큐 D 무시 · 함정② 원소가 0 하나일 때 `not h` 로 개수 판단 — 둘 다 처음부터 맞음.
#     🟢 `h.remove(max(h))` 뒤에 `heapq.heapify(h)` 를 다시 부른 것이 특히 맞다.
#        remove 는 중간 원소를 빼고 뒤를 당겨와 힙 성질을 깬다. 이걸 빼먹으면
#        이후 heappop 이 최솟값이 아닌 걸 꺼내서 멀리서 틀린 답이 나온다(찾기 매우 어려움).
#
#   ■ 🔴 하지만 성능에서 갈린다 — 이번 문제의 핵심
#     heappop(최솟값)은 O(log n) 인데 remove(max(h)) + heapify 는 O(n).
#     최댓값 삭제만 비싸서 전체가 O(n²) 가 된다. 실측:
#        n=2,500  0.064초 → 5,000  0.248초 → 10,000  0.913초 → 20,000  3.546초
#        (n 2배마다 시간 4배 = O(n²))  → 제약 최대치(연산 100만) 환산 약 37분
#     같은 100만 연산인데 D -1 만 쓰면 0.14초, D 1 만 쓰면 37분. 15,000배 차이.
#     원인은 remove 한 줄이다.
#
#   ■ 제가 깐 함정 11번은 "안 만났다"
#     11번은 **힙을 2개 쓸 때만** 생기는 함정(두 힙이 동기화되지 않음)이다.
#     힙 1개 + remove 로 가면 그 상황이 아예 안 생긴다.
#     피한 게 아니라 다른 길로 가서 안 만난 것 → 그래서 ② 기준 풀이를 같이 넣었다.
#     ②의 주석에 "왜 clear() 가 필요한가"가 적혀 있다. 그 기술은 다른 문제에서 계속 나온다.
#
#   ■ 새로 안 것
#     ① heapq 는 중간 원소를 지울 수 없다. remove 는 O(n) 이라 대안이 못 된다
#     ② 값은 못 지워도 **개수는 셀 수 있다** — 힙 2개 방식이 size 로 넘기는 요령
#     ③ 최대 힙 = 부호 뒤집어 넣기 (1단 기록 칸에 적어둔 것을 ②에서 실제로 씀)
#     ④ list.remove 는 힙 성질을 깬다 → heapify 재호출 필요
#
#   ■ 🔴 반복 교훈 2번째 사례 — "채점 통과 ≠ 정답"
#     10/13 더맵게: 반례 4개 있는 코드로 통과
#     10/15 이 문제: 최악 37분 걸리는 코드로 통과
#     **플랫폼 테스트셋이 느슨하다는 데이터가 두 건 쌓였다.**
#     → 제출 통과를 "맞았다"의 근거로 쓰지 않는다. 반례와 규모를 따로 재야 한다.
