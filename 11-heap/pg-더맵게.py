# 상태: 🟡 힙 1단 — 새 유형 첫 문제 (2026-10-13)
#
# ─────────────────────────────────────────────────────────────────────
# ■ 이 문제의 위치 (36분 되면 끝)
#   힙(heap) 유형의 입문 문제다. 스택/큐를 끝낸 다음 단계다.
#   새 유형이므로 백지가 아니다 — 아래에 "도구 설명"은 주고 "풀이"는 주지 않는다.
#
# ■ 문제 요약
#   scoville  : 음식들의 스코빌 지수(매운 정도) 배열
#   K         : 목표 지수
#
#   모든 음식의 스코빌 지수가 K 이상이 되게 만들어야 한다.
#   K 미만인 음식이 남아 있으면 아래 규칙으로 섞는다.
#
#       섞은 음식 = 가장 안 매운 음식 + (두 번째로 안 매운 음식 × 2)
#
#   섞은 횟수를 반환한다. 아무리 섞어도 전부 K 이상으로 못 만들면 -1.
#
#   예: scoville = [1, 2, 3, 9, 10, 12], K = 7  →  2
#
#     1회차: 가장 안 매운 1, 그다음 2 를 섞는다 → 1 + 2×2 = 5
#            남은 것 = [3, 5, 9, 10, 12]   (아직 3 이 7 미만)
#     2회차: 3 과 5 를 섞는다 → 3 + 5×2 = 13
#            남은 것 = [9, 10, 12, 13]     (전부 7 이상) → 끝
#
# ─────────────────────────────────────────────────────────────────────
# ■ 쓸 도구: heapq (파이썬 표준 모듈)
#
#   "항상 가장 작은 값을 빨리 꺼내야 하는" 상황을 위한 자료구조다.
#   정렬과 뭐가 다른가 — 정렬은 전체 순서를 만들고(느림),
#   힙은 "제일 작은 것 하나"만 책임진다(빠름).
#
#   import heapq
#
#   heapq.heapify(arr)      # 리스트를 제자리에서 힙으로 바꾼다. 반환값 없음(None)
#   heapq.heappop(h)        # 가장 작은 값을 꺼내서 반환. 꺼낸 만큼 길이가 줄어든다
#   heapq.heappush(h, x)    # x 를 넣는다
#   h[0]                    # 꺼내지 않고 "지금 가장 작은 값"만 본다
#   len(h)                  # 남은 개수
#
#   🔴 파이썬 heapq 는 최소 힙뿐이다 — 가장 "작은" 것만 꺼낼 수 있다.
#      가장 큰 것이 필요하면 넣을 때 부호를 뒤집는다(-x 로 넣고 꺼내서 다시 -를 붙임).
#      이 문제는 가장 작은 것만 필요하니 뒤집을 일이 없다.
#
#   🔴 heapify 는 반환값이 없다. `h = heapq.heapify(arr)` 로 쓰면 h 가 None 이 된다.
#
# ─────────────────────────────────────────────────────────────────────
# ■ 제약 조건 (여기에 설계가 들어 있다)
#   scoville 길이 : 2 ~ 1,000,000
#   각 지수       : 0 ~ 1,000,000
#   K             : 0 ~ 1,000,000,000
#
#   → 길이가 100만이다. "매번 정렬해서 앞의 두 개를 꺼낸다"로 쓰면
#     섞는 횟수 × 정렬 비용이 되어 반드시 시간초과가 난다.
#     이 숫자가 heapq 를 쓰라는 신호다.
#
# ■ 🔴 함정 3개 — 테스트 케이스가 각각을 잡는다
#   ① 섞을 음식이 1개만 남았을 때
#      K 미만인데 섞을 상대가 없다 → 더 못 한다(-1).
#      이 검사를 안 하면 heappop 두 번에서 터지거나 무한히 돈다.
#   ② 1개만 남았는데 그게 K 이상이면 성공이다
#      "1개 남음" 자체가 실패가 아니다. 값을 봐야 한다.
#   ③ K = 0 이면 처음부터 끝난 상태일 수 있다
#      0 도 0 이상이다. 한 번도 안 섞고 0 을 반환해야 한다.
#
# ■ 막히면 — 힌트 사다리 (위에서부터 하나씩만 연다)
#   1단계: 매번 필요한 건 "가장 작은 값 2개"다. 매번 전체를 정렬할 필요가 있나?
#   2단계: 섞은 결과를 다시 넣어야 한다. 넣은 것이 다음 차례에 가장 작을 수도 있다.
#   3단계: 반복을 멈추는 조건은 두 가지다 — 성공(가장 작은 게 K 이상)과 실패(섞을 게 없음).
#          이 두 개를 어디서 검사할지 정하면 구조가 끝난다.
#
#   20분이 지나면 멈추고 어디까지 갔는지 아래 기록 칸에 적는다.
#
# ⏱ 목표 20분
# ─────────────────────────────────────────────────────────────────────

import heapq


# ─────────────────────────────────────────────────────────────────────
# 최종 풀이 — 10/13 제출본을 10/15 에 직접 수정한 것
#
#   멈추는 조건이 딱 2개뿐이고, 둘 다 while 머리와 그 바로 아래에 모여 있다:
#     성공 = 가장 안 매운 것이 이미 K 이상  → while 조건이 거짓
#     실패 = 섞을 상대가 없다               → len(h) < 2
#
#   🔴 10/15 에 고친 것 3가지 (10/13 제출본과의 차이)
#     ① `if smallest == 0 and second == 0: return -1` 두 줄 삭제
#        → 이 줄이 [0,0,5] K=1 에서 -1 을 만들었다(정답 2). 아래 테스트 뒤 4개가 그 반례.
#          "0끼리 섞으면 영원히 0"이 걱정이었는데, 섞을 때마다 길이가 1 줄어드니
#          무한루프는 구조적으로 불가능하다. [0,0,0,0] 도 이 줄 없이 -1 이 된다.
#     ② `len(...) == 0` 검사를 꺼낸 뒤 → **꺼내기 전** `len(h) < 2` 로 옮김
#        → 둘 다 맞는 코드지만, 지금 형태가 "섞을 상대가 둘 이상인가"라는 질문 그대로다
#     ③ `h = list(scoville)` 복사 추가
#        → heapify 는 원본을 제자리에서 바꾼다. 복사 없이 같은 입력으로 두 번
#          테스트하면 두 번째 결과가 달라진다(제출용으로는 무관, 테스트에서는 걸린다)
#
#   출구가 늘어나면 틀릴 자리도 늘어난다 — 이번 문제에서 가져갈 가장 쓸모 있는 것.
# ─────────────────────────────────────────────────────────────────────
def solution(scoville, K):
    h = list(scoville)  # 원본을 건드리지 않는다
    heapq.heapify(h)

    answer = 0
    while h and h[0] < K:  # 가장 안 매운 것이 K 이상이면 전부 K 이상이다
        if len(h) < 2:  # 섞을 상대가 없다 → 더 못 한다
            return -1

        smallest = heapq.heappop(h)
        second = heapq.heappop(h)
        result = smallest + second * 2

        heapq.heappush(h, result)
        answer += 1

    return answer


if __name__ == "__main__":
    # 앞 8개 = 처음 만든 케이스 / 뒤 4개 = 10/13 제출본의 반례 (10/13 추가)
    cases = [
        (([1, 2, 3, 9, 10, 12], 7), 2),  # 공식 예제
        (([10, 20], 5), 0),  # 이미 전부 K 이상 — 한 번도 안 섞음
        (([1, 2], 3), 1),  # 🔴 함정② 1개 남았지만 K 이상이라 성공
        (([0, 7], 7), 1),  # 0 이 섞여도 성공하는 경우
        (([1, 1], 7), -1),  # 🔴 함정① 섞을 상대가 없어짐
        (([0, 0, 0, 0], 1), -1),  # 0 만 모여 있어 영원히 못 올림
        (([0, 0], 0), 0),  # 🔴 함정③ K=0 — 0 도 0 이상이다
        (([2, 2, 2, 2, 2], 10), 4),  # 섞은 결과가 다시 재료로 쓰임
        # ↓ 🔴 ③ ①의 반례 — "0끼리 섞어도 그 다음에 0 아닌 게 올라온다"
        (([0, 0, 5], 1), 2),  # 0+0=0 → [0,5] → 0+10=10 → 성공
        (([0, 0, 1], 1), 2),
        (([0, 0, 0, 100], 50), 3),
        (([0, 0, 3, 4], 10), 3),
    ]

    for (scoville, K), expected in cases:
        got = solution(scoville, K)
        assert got == expected, f"scoville={scoville} K={K}  기대={expected}  실제={got}"
    print(f"모든 케이스 통과 ({len(cases)}개 — 뒤 4개는 10/13 제출본이 틀렸던 반례)")


