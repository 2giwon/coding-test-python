#                 무한루프는 구조적으로 불가능하다. [0,0,0,0] 도 그 줄 없이 -1 이 된다.
#                 그 두 줄을 지운 상태로 테스트 17개 + 무작위 60,000건 교차검증 불일치 0건.
#   새로 안 것  : ① heapq — 정렬은 전체 순서를 만들고, 힙은 "제일 작은 것 하나"만 책임진다
#                 ② heapq 는 최소 힙뿐이다. 최대값이 필요하면 부호를 뒤집어 넣는다
#                   (다음 문제 이중우선순위큐 42628 에서 바로 이 제약에 부딪힌다)
#                 ③ heapify 는 반환값이 없다(제자리 변경)
#                 ④ -1 검사는 "꺼낸 다음"에 길이를 보는 위치가 맞다 ← 이건 처음부터 맞게 썼다
