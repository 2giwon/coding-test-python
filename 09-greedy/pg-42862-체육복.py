# ① 문제
# =====================================================================
#   점심시간에 도둑이 들어, 일부 학생이 체육복을 도난당했다.
#   다행히 여벌 체육복이 있는 학생이 이들에게 체육복을 빌려주려 한다.
#
#   학생들의 번호는 체격 순으로 매겨져 있어서,
#   **자신의 번호에서 바로 앞번호 또는 바로 뒷번호 학생에게만** 빌려줄 수 있다.
#
#   예를 들어 4번 학생은 3번 또는 5번 학생에게만 빌려줄 수 있다.
#   체육복이 없으면 수업을 들을 수 없다.
#
#   전체 학생 수 n,
#   체육복을 도난당한 학생들의 번호 배열 lost,
#   여벌 체육복을 가져온 학생들의 번호 배열 reserve 가 주어질 때,
#   **체육수업을 들을 수 있는 학생의 최댓값**을 return 하라.
#
#   🔴 여벌 체육복을 가져온 학생이 **도난도 당했을 수 있다.**
#      이때 그 학생은 남에게 빌려줄 수 없다 (자기가 입어야 하므로).
#      단, 빌려줄 수 있는 학생이 두 명이면 한 명에게만 빌려줄 수 있다.
#
# ■ 공식 예제
#   n = 5,  lost = [2, 4],  reserve = [1, 3, 5]   →   5
#   n = 5,  lost = [2, 4],  reserve = [3]         →   4
#   n = 3,  lost = [3],     reserve = [1]         →   2
#
# ■ 예제 1번 손추적
#   학생 5명. 2번과 4번이 도난당했다. 1번, 3번, 5번이 여벌을 가져왔다.
#     - 1번은 2번에게 빌려줄 수 있다 (2번 해결)
#     - 3번은 2번 또는 4번에게 빌려줄 수 있다
#     - 5번은 4번에게 빌려줄 수 있다 (4번 해결)
#   2번과 4번이 모두 해결되므로 5명 전원이 수업을 듣는다.
#
#   🟡 여기서 눈여겨볼 것 — 3번은 2번에게 줘도 되고 4번에게 줘도 되는데,
#      **그 선택이 전체 결과를 바꿀 수 있는가?** 이 문제의 핵심이 여기다.
#      예제 1번은 1번과 5번이 양쪽을 덮어 줘서 3번이 뭘 해도 5가 나온다.
#      그렇지 않은 입력이 있다면 어떤 모양일까.
#
#
