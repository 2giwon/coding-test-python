# =====================================================================
#
# ■ 그리디(탐욕법)란 무엇인가
#
#   전체 경우를 다 따져 보지 않고, **지금 이 순간 가장 좋아 보이는 것을
#   고르고 되돌리지 않는 것**이다. 한 번 정하면 뒤에서 다시 안 건드린다.
#
#   지금까지 쓴 도구들과의 차이를 보면 성격이 분명해진다.
#     - 완전탐색 : 모든 경우를 다 만들어 보고 그중 제일 좋은 것을 고른다
#     - DP       : 작은 문제의 답을 **저장해 두고** 큰 문제를 조립한다
#     - 그리디   : 한 번 훑으면서 그 자리에서 정하고 끝낸다. 저장도 복귀도 없다
#
#   그래서 그리디는 세 가지 중 가장 빠르고 가장 짧다.
#   대신 **틀릴 수 있다.** 지금 좋아 보이는 선택이 나중에 발목을 잡는 문제가
#   훨씬 많다. 그리디의 어려움은 코드가 아니라 **"이 문제에 그리디를 써도
#   되는가"를 판단하는 것**이다.
#
# ■ 완전탐색은 왜 안 되나
#
#   이 문제를 완전탐색으로 풀면 이렇게 된다 — 여벌을 가진 학생 각자가
#   "왼쪽에 준다 / 오른쪽에 준다 / 안 준다" 셋 중 하나를 고른다.
#   여벌 학생이 k명이면 경우의 수가 3^k 이다.
#
#   제약을 보면 n 이 최대 30이고, reserve 의 길이는 최대 n 이다.
#   3^30 = 약 2해(2 × 10^14)다. 1초에 1억 번을 센다 해도 20일이 넘는다.
#
#   🟡 단, 이 숫자를 믿고 "그래서 그리디구나"로 가면 안 된다.
#      n 이 30밖에 안 되므로 DP 도 충분히 돈다. 제약은 **후보를 줄여줄 뿐
#      도구를 골라주지 않는다.** (2026-10-20 유형 식별 드릴에서 확인한 것)
#      도구를 고르는 건 다음 항목이다.
#
# ■ 그리디를 믿어도 되는 조건 두 개
#
#   그리디가 정답을 내는 문제에는 공통점이 있다.
#
#   (가) **지금 고른 것이 나중 선택의 범위를 줄이지 않는다**
#        내가 지금 A를 고른 탓에 나중에 B를 못 고르게 되면, A를 고른 게
#        손해였을 수 있다. 그러면 되돌아가야 하므로 그리디가 깨진다.
#
#   (나) **지금 고르는 것이 최선이라는 걸 그 자리에서 증명할 수 있다**
#        "어떤 정답이 내 선택과 다르다면, 그 정답을 내 선택으로 바꿔치기해도
#        답이 나빠지지 않는다"를 말할 수 있어야 한다.
#
# ■ 이 문제가 그 조건을 만족하는 이유
#
#   핵심은 문제 지문의 이 한 줄이다 —
#   **"바로 앞번호 또는 바로 뒷번호 학생에게만 빌려줄 수 있다."**
#
#   즉 여벌을 가진 학생 r 의 영향 범위는 r-1 과 r+1, **딱 2칸뿐**이다.
#   r 이 누구에게 주든, 번호가 r+2 이상 떨어진 학생들의 사정은
#   전혀 바뀌지 않는다. 영향이 멀리 번지지 않는다.
#
#   그래서 학생들을 **번호 순서대로 한 번 훑으면서**, 지금 자리에서
#   처리할 수 있는 것을 처리하고 넘어가는 방식이 성립한다.
#   뒤쪽에서 내린 결정이 앞쪽으로 되돌아와 결과를 바꾸지 않기 때문이다.
#
#   🔴 **"번호 순서대로 훑는다"까지가 이 설명이 알려주는 전부다.**
#      그 안에서 매 순간 **무엇을 고르는 것이 지금 최선인지**는
#      직접 정해야 한다. 예제 1번 손추적의 🟡 표시가 그 질문이었다.
#      선택지가 두 개일 때 어느 쪽을 고르느냐로 답이 갈리는 입력이
#      실제로 존재한다. 아래 테스트가 그걸 잡아낸다.
